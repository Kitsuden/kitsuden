import type { CollectionInfo, GeneratedFile, GenerateOptions } from "../index.js";

const toPascal = (s: string) =>
  s
    .split(/[_\-]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join("");

const toCamel = (s: string) => {
  const p = toPascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};

export function generateReact(options: GenerateOptions): GeneratedFile[] {
  const { collection, type, baseUrl = "" } = options;
  const pascalName = toPascal(collection.slug);
  const camelName = toCamel(collection.slug);
  const endpoint = `${baseUrl}/api/items/${collection.slug}`;

  const files: GeneratedFile[] = [];

  if (type === "types" || type === "all") {
    files.push(generateTypes(collection, pascalName));
  }

  if (type === "hook" || type === "all") {
    files.push(generateReactHooks(collection, pascalName, camelName, endpoint));
  }

  if (type === "component" || type === "all") {
    files.push(generateReactComponent(collection, pascalName, camelName));
  }

  if (type === "form" || type === "all") {
    files.push(generateReactForm(collection, pascalName, camelName, endpoint));
  }

  return files;
}

function generateTypes(collection: CollectionInfo, pascalName: string): GeneratedFile {
  const fields = collection.columns
    .map((col) => {
      const tsType = mapToTsType(col.type);
      const optional = col.required ? "" : "?";
      return `  ${col.name}${optional}: ${tsType};`;
    })
    .join("\n");

  const content = `// Generated by Kitsuden for collection "${collection.slug}"
// Do not edit manually — regenerate with: kitsuden generate --collection ${collection.slug} --framework react

export interface ${pascalName} {
${fields}
}

export interface ${pascalName}Page {
  docs: ${pascalName}[];
  totalDocs: number;
  page: number;
  limit: number;
  hasNextPage: boolean;
}
`;

  return { filename: `${collection.slug}.types.ts`, content, language: "typescript" };
}

function generateReactHooks(
  collection: CollectionInfo,
  pascalName: string,
  _camelName: string,
  endpoint: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";

  const content = `// Generated by Kitsuden for collection "${collection.slug}"
import { useState, useEffect, useCallback } from "react";
import type { ${pascalName}, ${pascalName}Page } from "./${collection.slug}.types";

const API_BASE = "${endpoint}";

/**
 * Hook to list ${collection.name} with pagination and search.
 */
export function use${pascalName}List(options?: { page?: number; limit?: number; search?: string }) {
  const [data, setData] = useState<${pascalName}Page | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  const fetchList = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const params = new URLSearchParams();
      if (options?.page) params.set("page", String(options.page));
      if (options?.limit) params.set("limit", String(options.limit));
      if (options?.search) params.set("search", options.search);
      const res = await fetch(\`\${API_BASE}?\${params.toString()}\`);
      if (!res.ok) throw new Error(await res.text());
      const json = await res.json();
      setData(json);
    } catch (err: any) {
      setError(err);
    } finally {
      setLoading(false);
    }
  }, [options?.page, options?.limit, options?.search]);

  useEffect(() => { fetchList(); }, [fetchList]);

  return { data, loading, error, refetch: fetchList };
}

/**
 * Hook to get a single ${collection.name} by ${pk}.
 */
export function use${pascalName}ById(${pk}: string | undefined) {
  const [data, setData] = useState<${pascalName} | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  useEffect(() => {
    if (!${pk}) return;
    let cancelled = false;
    setLoading(true);
    fetch(\`\${API_BASE}/${pk}\`)
      .then(async (res) => {
        if (!res.ok) throw new Error(await res.text());
        return res.json();
      })
      .then((json) => { if (!cancelled) setData(json); })
      .catch((err) => { if (!cancelled) setError(err); })
      .finally(() => { if (!cancelled) setLoading(false); });
    return () => { cancelled = true; };
  }, [${pk}]);

  return { data, loading, error };
}

/**
 * Hook to create a new ${collection.name}.
 */
export function useCreate${pascalName}() {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  const create = useCallback(async (payload: Omit<${pascalName}, "${pk}">) => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(API_BASE, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });
      if (!res.ok) throw new Error(await res.text());
      return (await res.json()) as ${pascalName};
    } catch (err: any) {
      setError(err);
      throw err;
    } finally {
      setLoading(false);
    }
  }, []);

  return { create, loading, error };
}

/**
 * Hook to update a ${collection.name}.
 */
export function useUpdate${pascalName}() {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  const update = useCallback(async (${pk}: string, payload: Partial<${pascalName}>) => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(\`\${API_BASE}/${pk}\`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });
      if (!res.ok) throw new Error(await res.text());
      return (await res.json()) as ${pascalName};
    } catch (err: any) {
      setError(err);
      throw err;
    } finally {
      setLoading(false);
    }
  }, []);

  return { update, loading, error };
}

/**
 * Hook to delete a ${collection.name}.
 */
export function useDelete${pascalName}() {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<Error | null>(null);

  const remove = useCallback(async (${pk}: string) => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch(\`\${API_BASE}/${pk}\`, { method: "DELETE" });
      if (!res.ok) throw new Error(await res.text());
      return await res.json();
    } catch (err: any) {
      setError(err);
      throw err;
    } finally {
      setLoading(false);
    }
  }, []);

  return { remove, loading, error };
}
`;

  return { filename: `use${pascalName}.ts`, content, language: "typescript" };
}

function generateReactComponent(
  collection: CollectionInfo,
  pascalName: string,
  camelName: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";
  const displayField =
    collection.columns.find((c) => c.name === "title" || c.name === "name" || c.name === "label")
      ?.name || pk;

  const content = `// Generated by Kitsuden for collection "${collection.slug}"
import React from "react";
import { use${pascalName}List } from "./use${pascalName}";
import type { ${pascalName} } from "./${collection.slug}.types";

interface ${pascalName}ListProps {
  onSelect?: (item: ${pascalName}) => void;
  pageSize?: number;
}

export function ${pascalName}List({ onSelect, pageSize = 50 }: ${pascalName}ListProps) {
  const { data, loading, error, refetch } = use${pascalName}List({ limit: pageSize });

  if (loading) return <div>Loading ${collection.name}...</div>;
  if (error) return <div style={{ color: "red" }}>Error: {error.message} <button onClick={refetch}>Retry</button></div>;
  if (!data?.docs?.length) return <div>No ${collection.name} found.</div>;

  return (
    <div className="${camelName}-list">
      <h2>${collection.name}</h2>
      <ul>
        {data.docs.map((item) => (
          <li key={item.${pk}} onClick={() => onSelect?.(item)} style={{ cursor: onSelect ? "pointer" : "default" }}>
            {item.${displayField} || \`#\${item.${pk}}\`}
          </li>
        ))}
      </ul>
      {data.hasNextPage && (
        <button onClick={() => {/* pagination logic */}}>Load more</button>
      )}
    </div>
  );
}
`;

  return { filename: `${pascalName}List.tsx`, content, language: "tsx" };
}

function generateReactForm(
  collection: CollectionInfo,
  pascalName: string,
  _camelName: string,
  _endpoint: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";
  const editableColumns = collection.columns.filter((c) => c.name !== pk && !c.isRelation);

  const fields = editableColumns
    .map((col) => {
      const inputType = mapToInputType(col.type);
      return `          <label style={{ display: "block", marginBottom: 8 }}>
            ${toPascal(col.name)}
            <input
              type="${inputType}"
              name="${col.name}"
              required={${col.required}}
              style={{ display: "block", width: "100%", padding: 8, marginTop: 4 }}
            />
          </label>`;
    })
    .join("\n");

  const content = `// Generated by Kitsuden for collection "${collection.slug}"
import React, { useState, FormEvent } from "react";
import { useCreate${pascalName} } from "./use${pascalName}";
import type { ${pascalName} } from "./${collection.slug}.types";

interface ${pascalName}FormProps {
  onSuccess?: (item: ${pascalName}) => void;
  onCancel?: () => void;
}

export function ${pascalName}Form({ onSuccess, onCancel }: ${pascalName}FormProps) {
  const { create, loading, error } = useCreate${pascalName}();

  const handleSubmit = async (e: FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    const formData = new FormData(e.currentTarget);
    const payload = Object.fromEntries(formData.entries());
    try {
      const item = await create(payload as any);
      onSuccess?.(item);
      e.currentTarget.reset();
    } catch {
      // error handled by hook
    }
  };

  return (
    <form onSubmit={handleSubmit} style={{ maxWidth: 480 }}>
      <h2>Create ${collection.name}</h2>
${fields}
      <div style={{ marginTop: 16 }}>
        <button type="submit" disabled={loading}>
          {loading ? "Saving..." : "Save"}
        </button>
        {onCancel && (
          <button type="button" onClick={onCancel} style={{ marginLeft: 8 }}>
            Cancel
          </button>
        )}
      </div>
      {error && <p style={{ color: "red" }}>{error.message}</p>}
    </form>
  );
}
`;

  return { filename: `${pascalName}Form.tsx`, content, language: "tsx" };
}

// ── Helpers ──

function mapToTsType(dbType: string): string {
  const t = dbType.toLowerCase();
  if (
    t.includes("int") ||
    t.includes("float") ||
    t.includes("double") ||
    t.includes("real") ||
    t.includes("numeric") ||
    t.includes("decimal")
  )
    return "number";
  if (t.includes("bool")) return "boolean";
  if (t.includes("json")) return "Record<string, unknown>";
  if (t.includes("timestamp") || t.includes("date")) return "string";
  return "string";
}

function mapToInputType(dbType: string): string {
  const t = dbType.toLowerCase();
  if (t.includes("bool")) return "checkbox";
  if (t.includes("int") || t.includes("float") || t.includes("double") || t.includes("real"))
    return "number";
  if (t.includes("email")) return "email";
  if (t.includes("url")) return "url";
  return "text";
}
