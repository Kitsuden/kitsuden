import type { CollectionInfo, GeneratedFile, GenerateOptions } from "../index.js";

const toPascal = (s: string) =>
  s
    .split(/[_\-]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join("");

const toCamel = (s: string) => {
  const p = toPascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};

export function generateSvelte(options: GenerateOptions): GeneratedFile[] {
  const { collection, type, baseUrl = "" } = options;
  const pascalName = toPascal(collection.slug);
  const camelName = toCamel(collection.slug);
  const endpoint = `${baseUrl}/api/items/${collection.slug}`;

  const files: GeneratedFile[] = [];

  if (type === "types" || type === "all") {
    files.push(generateSvelteTypes(collection, pascalName));
  }

  if (type === "hook" || type === "all") {
    files.push(generateSvelteStores(collection, pascalName, camelName, endpoint));
  }

  if (type === "component" || type === "all") {
    files.push(generateSvelteComponent(collection, pascalName, camelName));
  }

  if (type === "form" || type === "all") {
    files.push(generateSvelteForm(collection, pascalName, camelName, endpoint));
  }

  return files;
}

function generateSvelteTypes(collection: CollectionInfo, pascalName: string): GeneratedFile {
  const fields = collection.columns
    .map((col) => {
      const tsType = mapToTsType(col.type);
      const optional = col.required ? "" : "?";
      return `  ${col.name}${optional}: ${tsType};`;
    })
    .join("\n");

  const content = `// Generated by Kitsuden for collection "${collection.slug}"

export interface ${pascalName} {
${fields}
}

export interface ${pascalName}Page {
  docs: ${pascalName}[];
  totalDocs: number;
  page: number;
  limit: number;
  hasNextPage: boolean;
}
`;

  return { filename: `${collection.slug}.types.ts`, content, language: "typescript" };
}

function generateSvelteStores(
  collection: CollectionInfo,
  pascalName: string,
  camelName: string,
  endpoint: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";

  const content = `// Generated by Kitsuden for collection "${collection.slug}"
import { writable, derived } from "svelte/store";
import type { ${pascalName}, ${pascalName}Page } from "./${collection.slug}.types";

const API_BASE = "${endpoint}";

// ── List Store ──
function createListStore() {
  const { subscribe, set, update } = writable<{ data: ${pascalName}Page | null; loading: boolean; error: Error | null }>({
    data: null,
    loading: false,
    error: null,
  });

  return {
    subscribe,
    async fetchList(options?: { page?: number; limit?: number; search?: string }) {
      update((s) => ({ ...s, loading: true, error: null }));
      try {
        const params = new URLSearchParams();
        if (options?.page) params.set("page", String(options.page));
        if (options?.limit) params.set("limit", String(options.limit));
        if (options?.search) params.set("search", options.search);
        const res = await fetch(\`\${API_BASE}?\${params.toString()}\`);
        if (!res.ok) throw new Error(await res.text());
        const json = await res.json();
        set({ data: json, loading: false, error: null });
      } catch (err: any) {
        set({ data: null, loading: false, error: err });
      }
    },
  };
}

export const ${camelName}List = createListStore();

// ── Detail Store ──
function createDetailStore() {
  const { subscribe, set } = writable<{ data: ${pascalName} | null; loading: boolean; error: Error | null }>({
    data: null,
    loading: false,
    error: null,
  });

  return {
    subscribe,
    async fetchById(${pk}: string) {
      set({ data: null, loading: true, error: null });
      try {
        const res = await fetch(\`\${API_BASE}/${pk}\`);
        if (!res.ok) throw new Error(await res.text());
        const json = await res.json();
        set({ data: json, loading: false, error: null });
      } catch (err: any) {
        set({ data: null, loading: false, error: err });
      }
    },
    reset() {
      set({ data: null, loading: false, error: null });
    },
  };
}

export const ${camelName}Detail = createDetailStore();

// ── Create Action ──
export async function create${pascalName}(payload: Omit<${pascalName}, "${pk}">): Promise<${pascalName}> {
  const res = await fetch(API_BASE, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  if (!res.ok) throw new Error(await res.text());
  return res.json();
}

// ── Update Action ──
export async function update${pascalName}(${pk}: string, payload: Partial<${pascalName}>): Promise<${pascalName}> {
  const res = await fetch(\`\${API_BASE}/${pk}\`, {
    method: "PATCH",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  if (!res.ok) throw new Error(await res.text());
  return res.json();
}

// ── Delete Action ──
export async function delete${pascalName}(${pk}: string): Promise<void> {
  const res = await fetch(\`\${API_BASE}/${pk}\`, { method: "DELETE" });
  if (!res.ok) throw new Error(await res.text());
}
`;

  return { filename: `${camelName}Store.ts`, content, language: "typescript" };
}

function generateSvelteComponent(
  collection: CollectionInfo,
  pascalName: string,
  camelName: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";
  const displayField =
    collection.columns.find((c) => c.name === "title" || c.name === "name" || c.name === "label")
      ?.name || pk;

  const content = `<!-- Generated by Kitsuden for collection "${collection.slug}" -->
<script lang="ts">
  import { ${camelName}List } from "./${camelName}Store";
  import type { ${pascalName} } from "./${collection.slug}.types";

  export let pageSize = 50;
  export let onSelect: ((item: ${pascalName}) => void) | undefined = undefined;

  ${camelName}List.fetchList({ limit: pageSize });
</script>

<div class="${camelName}-list">
  <h2>${collection.name}</h2>

  {#if $${camelName}List.loading}
    <p>Loading ${collection.name}...</p>
  {:else if $${camelName}List.error}
    <p style="color: red">
      Error: {$${camelName}List.error.message}
      <button on:click={() => ${camelName}List.fetchList({ limit: pageSize })}>Retry</button>
    </p>
  {:else if !$${camelName}List.data?.docs?.length}
    <p>No ${collection.name} found.</p>
  {:else}
    <ul>
      {#each $${camelName}List.data.docs as item}
        <li
          on:click={() => onSelect?.(item)}
          style="cursor: {onSelect ? 'pointer' : 'default'}"
        >
          {item.${displayField} || \`#\${item.${pk}}\`}
        </li>
      {/each}
    </ul>
    {#if $${camelName}List.data.hasNextPage}
      <button>Load more</button>
    {/if}
  {/if}
</div>
`;

  return { filename: `${pascalName}List.svelte`, content, language: "svelte" };
}

function generateSvelteForm(
  collection: CollectionInfo,
  pascalName: string,
  camelName: string,
  _endpoint: string
): GeneratedFile {
  const pk = collection.primaryKey || "id";
  const editableColumns = collection.columns.filter((c) => c.name !== pk && !c.isRelation);

  const fields = editableColumns
    .map((col) => {
      const inputType = mapToInputType(col.type);
      return `  <label style="display: block; margin-bottom: 8px">
    ${toPascal(col.name)}
    <input
      bind:value={form.${col.name}}
      type="${inputType}"
      required={${col.required}}
      style="display: block; width: 100%; padding: 8px; margin-top: 4px"
    />
  </label>`;
    })
    .join("\n");

  const formInit = editableColumns
    .map((col) => `  ${col.name}: ${col.type.toLowerCase().includes("bool") ? "false" : `""`},`)
    .join("\n");

  const content = `<!-- Generated by Kitsuden for collection "${collection.slug}" -->
<script lang="ts">
  import { createEventDispatcher } from "svelte";
  import { create${pascalName} } from "./${camelName}Store";
  import type { ${pascalName} } from "./${collection.slug}.types";

  const dispatch = createEventDispatcher<{ success: ${pascalName}; cancel: void }>();

  let form = {
${formInit}
  };

  let loading = false;
  let error: Error | null = null;

  async function handleSubmit() {
    loading = true;
    error = null;
    try {
      const item = await create${pascalName}(form);
      dispatch("success", item);
      form = {
${formInit}
      };
    } catch (err: any) {
      error = err;
    } finally {
      loading = false;
    }
  }
</script>

<form on:submit|preventDefault={handleSubmit} style="max-width: 480px">
  <h2>Create ${collection.name}</h2>
${fields}
  <div style="margin-top: 16px">
    <button type="submit" disabled={loading}>
      {loading ? "Saving..." : "Save"}
    </button>
    <button type="button" on:click={() => dispatch("cancel")} style="margin-left: 8px">
      Cancel
    </button>
  </div>
  {#if error}
    <p style="color: red">{error.message}</p>
  {/if}
</form>
`;

  return { filename: `${pascalName}Form.svelte`, content, language: "svelte" };
}

function mapToTsType(dbType: string): string {
  const t = dbType.toLowerCase();
  if (
    t.includes("int") ||
    t.includes("float") ||
    t.includes("double") ||
    t.includes("real") ||
    t.includes("numeric") ||
    t.includes("decimal")
  )
    return "number";
  if (t.includes("bool")) return "boolean";
  if (t.includes("json")) return "Record<string, unknown>";
  if (t.includes("timestamp") || t.includes("date")) return "string";
  return "string";
}

function mapToInputType(dbType: string): string {
  const t = dbType.toLowerCase();
  if (t.includes("bool")) return "checkbox";
  if (t.includes("int") || t.includes("float") || t.includes("double") || t.includes("real"))
    return "number";
  if (t.includes("email")) return "email";
  if (t.includes("url")) return "url";
  return "text";
}
