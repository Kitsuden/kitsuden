/** `{ a: 1, b: "x" }` from the fields, with a value picker. */
export function objectLiteral(fields: KonField[], value: (f: KonField) => string): string {
  if (fields.length === 0) return "{}";
  return `{ ${fields.map((f) => `${f.name}: ${value(f)}`).join(", ")} }`;
}

/** Row of the Markdown table of fields in README.md and AGENTS.md. */
export function docRow(f: KonField): string {
  return `| \`${f.name}\` | \`${f.column}\` | ${f.type} | \`${SQL_TYPE[f.type]}\` | ${f.required ? "yes" : "no (nullable)"} |`;
}

