/**
 * `kitsuden make kon <name> --fields "<spec>"` — the kon's own columns
 * ============================================================================
 *
 * The spec is a comma-separated list of `name:type`, with `!` after the type for a required field:
 *
 *   --fields "title:string!,price:number,stock:integer,published:boolean,dueOn:date,meta:json"
 *
 * Names are camelCase (`dueOn`): that is the name in TypeScript, zod and the API. The SQL column is
 * its snake_case (`due_on`), the convention of the template and of the real kons.
 *
 *   type       SQL                Drizzle                                    zod (input)
 *   string     varchar(200)       varchar(n, { length: 200 })                z.string().trim().max(200)   (`!`: .min(1))
 *   text       text               text(n)                                    z.string().max(100_000)      (`!`: .min(1))
 *   integer    integer            integer(n)                                 z.int32()
 *   number     numeric(19, 4)     numeric(n, { precision: 19, scale: 4,     z.number().gt(-1e15).lt(1e15)
 *                                   mode: "number" })
 *   boolean    boolean            boolean(n)                                 z.boolean()
 *   date       date               date(n)               ("YYYY-MM-DD")       z.iso.date()
 *   datetime   timestamptz        timestamp(n, { withTimezone: true })       z.iso.datetime({ offset: true })
 *   json       jsonb              jsonb(n).$type<JsonValue>()                object or array
 *   uuid       uuid               uuid(n)                                    z.guid()
 *
 * `number` is an EXACT decimal (numeric(19, 4), the precision the real kons use for money and
 * amounts): 15 digits before the point, 4 after (more are rounded by Postgres). It travels as a JSON
 * number. For whole numbers (counts, positions) use `integer` (32-bit).
 *
 * A field without `!` is nullable: optional in create, `null` accepted. Update takes every field
 * as optional (a required field cannot be set to null).
 */

export const FIELD_TYPES = [
  "string",
  "text",
  "integer",
  "number",
  "boolean",
  "date",
  "datetime",
  "json",
  "uuid",
] as const;
export type FieldType = (typeof FIELD_TYPES)[number];

export interface KonField {
  /** camelCase: TypeScript, zod, API. */
  name: string;
  /** snake_case: SQL column. */
  column: string;
  type: FieldType;
  required: boolean;
}

/** Generated by the template whatever the spec says: id, status (publishing + row security), timestamps. */
export const RESERVED_FIELDS = ["id", "status", "createdAt", "updatedAt"] as const;

/** PostgreSQL reserved keywords: unusable as an unquoted column name in the migration. */
const SQL_RESERVED = new Set(
  (
    "all analyse analyze and any array as asc asymmetric authorization binary both case cast check " +
    "collate collation column concurrently constraint create cross current_catalog current_date " +
    "current_role current_schema current_time current_timestamp current_user default deferrable desc " +
    "distinct do else end except false fetch for foreign freeze from full grant group having ilike in " +
    "initially inner intersect into is isnull join lateral leading left like limit localtime " +
    "localtimestamp natural not notnull null offset on only or order outer overlaps placing primary " +
    "references returning right select session_user similar some symmetric system_user table " +
    "tablesample then to trailing true union unique user using variadic verbose when where window with"
  ).split(" ")
);

/** Names that would break the generated TypeScript objects. */
const JS_RESERVED = new Set(["constructor", "prototype", "toString", "valueOf", "hasOwnProperty"]);

const NAME = /^[a-z][a-zA-Z0-9]*$/;

export const snakeColumn = (name: string) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const camelFromAny = (name: string) =>
  name.replace(/[_-]+([a-zA-Z0-9])/g, (_, ch: string) => ch.toUpperCase());

/**
 * Parses `--fields`. Throws an Error with a message for humans on the first problem, so nothing
 * is written when the spec is wrong.
 */
export function parseFields(spec: string): KonField[] {
  const usage = `Expected --fields "name:type[!],…", e.g. "title:string!,price:number". Types: ${FIELD_TYPES.join(", ")}.`;
  if (spec.trim() === "") throw new Error(`--fields is empty. ${usage}`);
  const fields: KonField[] = [];
  const byColumn = new Map<string, string>();
  for (const raw of spec.split(",")) {
    const entry = raw.trim();
    if (entry === "")
      throw new Error(`--fields has an empty entry (two commas in a row?). ${usage}`);
    const m = entry.match(/^([^:\s]+)\s*:\s*([A-Za-z]+)\s*(!?)$/);
    if (!m) throw new Error(`Invalid field "${entry}". ${usage}`);
    const [, name, type, bang] = m as unknown as [string, string, string, string];
    if (RESERVED_FIELDS.some((r) => r === camelFromAny(name) || snakeColumn(r) === name)) {
      throw new Error(
        `Field "${name}" is reserved: every generated kon already has ${RESERVED_FIELDS.join(", ")} ` +
          `(status is draft/published and drives the public read). Pick another name.`
      );
    }
    if (!NAME.test(name)) {
      const hint = camelFromAny(name);
      throw new Error(
        `Invalid field name "${name}": use camelCase letters and digits, starting with a lowercase letter` +
          (NAME.test(hint) ? ` (e.g. "${hint}"; the SQL column is "${snakeColumn(hint)}").` : ".")
      );
    }
    if (name.length > 50) throw new Error(`Field name "${name}" is longer than 50 characters.`);
    const column = snakeColumn(name);
    if (SQL_RESERVED.has(column)) {
      throw new Error(
        `Field "${name}" is a reserved word in SQL ("${column}"). Pick another name.`
      );
    }
    if (JS_RESERVED.has(name)) {
      throw new Error(
        `Field "${name}" would clash with a JavaScript object property. Pick another name.`
      );
    }
    if (!(FIELD_TYPES as readonly string[]).includes(type)) {
      throw new Error(`Unknown type "${type}" in "${entry}". Types: ${FIELD_TYPES.join(", ")}.`);
    }
    const clash = byColumn.get(column);
    if (clash) {
      throw new Error(
        clash === name
          ? `Field "${name}" is declared twice.`
          : `Fields "${clash}" and "${name}" would both be the SQL column "${column}".`
      );
    }
    byColumn.set(column, name);
    fields.push({ name, column, type: type as FieldType, required: bang === "!" });
  }
  return fields;
}

