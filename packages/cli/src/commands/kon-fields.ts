/** The Drizzle builder functions the schema file must import for these fields. */
export function drizzleImports(fields: KonField[]): string[] {
  const fn: Record<FieldType, string> = {
    string: "varchar",
    text: "text",
    integer: "integer",
    number: "numeric",
    boolean: "boolean",
    date: "date",
    datetime: "timestamp",
    json: "jsonb",
    uuid: "uuid",
  };
  // The template always uses these for id, status and the timestamps.
  const set = new Set([
    "pgTable",
    "timestamp",
    "uuid",
    "varchar",
    ...fields.map((f) => fn[f.type]),
  ]);
  return [...set].sort();
}

export function drizzleColumn(f: KonField): string {
  const n = JSON.stringify(f.column);
  const base: Record<FieldType, string> = {
    string: `varchar(${n}, { length: 200 })`,
    text: `text(${n})`,
    integer: `integer(${n})`,
    number: `numeric(${n}, { precision: 19, scale: 4, mode: "number" })`,
    boolean: `boolean(${n})`,
    date: `date(${n})`,
    datetime: `timestamp(${n}, { withTimezone: true })`,
    json: `jsonb(${n}).$type<JsonValue>()`,
    uuid: `uuid(${n})`,
  };
  return `  ${f.name}: ${base[f.type]}${f.required ? ".notNull()" : ""},`;
}

const SQL_TYPE: Record<FieldType, string> = {
  string: "varchar(200)",
  text: "text",
  integer: "integer",
  number: "numeric(19, 4)",
  boolean: "boolean",
  date: "date",
  datetime: "timestamptz",
  json: "jsonb",
  uuid: "uuid",
};

/** `  name        type NOT NULL,` aligned like the template's columns (12 wide). */
export function sqlColumn(f: KonField): string {
  const pad = f.column.length >= 12 ? `${f.column} ` : f.column.padEnd(12);
  return `  ${pad}${SQL_TYPE[f.type]}${f.required ? " NOT NULL" : ""},`;
}

const ZOD: Record<FieldType, (required: boolean) => string> = {
  string: (r) => (r ? "z.string().trim().min(1).max(200)" : "z.string().trim().max(200)"),
  text: (r) => (r ? "z.string().min(1).max(100_000)" : "z.string().max(100_000)"),
  integer: () => "z.int32()",
  number: () => "z.number().gt(-1e15).lt(1e15)",
  boolean: () => "z.boolean()",
  date: () => "z.iso.date()",
  datetime: () => "z.iso.datetime({ offset: true })",
  json: () => "Json",
  uuid: () => "z.guid()",
};

/** A line of the `Create` object (required → as is; optional → `.nullable().optional()`). */
export function zodInput(f: KonField): string {
  return `  ${f.name}: ${ZOD[f.type](f.required)}${f.required ? "" : ".nullable().optional()"},`;
}

/** A line of the `Item` output object. */
export function zodOutput(f: KonField): string {
  const out: Record<FieldType, string> = {
    string: "z.string()",
    text: "z.string()",
    integer: "z.number().int()",
    number: "z.number()",
    boolean: "z.boolean()",
    date: "z.iso.date()",
    datetime: "z.string().datetime({ offset: true })",
    json: "Json",
    uuid: "z.guid()",
  };
  return `  ${f.name}: ${out[f.type]}${f.required ? "" : ".nullable()"},`;
}

/** The value for `.values({...})` in create: dates parsed, absent optionals stored as null. */
export function insertValue(f: KonField): string {
  const v = `body.${f.name}`;
  if (f.type === "datetime") {
    return f.required ? `new Date(${v})` : `${v} == null ? null : new Date(${v})`;
  }
  return f.required ? v : `${v} ?? null`;
}

