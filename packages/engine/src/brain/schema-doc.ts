/**
 * KITSUDEN Brain — Layer 3: Schema document (BRAIN.md)
 * ============================================================================
 *
 * Generates BRAIN.md: the "schema" of the Karpathy method. It is a
 * configuration document that turns any AI (local, API or CLI) into a
 * DISCIPLINED maintainer of the wiki, not a generic chatbot.
 *
 * The output is 100% deterministic (same project → same BRAIN.md). A local
 * AI (Claude Code, Cursor, Ollama with tools) can read this file
 * and run the 4 operations following explicit rules.
 */

export interface BrainSchemaOptions {
  projectName?: string;
  wikiPath?: string;
}

/** Returns the content of BRAIN.md as a deterministic string. */
export function generateBrainSchemaDoc(options: BrainSchemaOptions = {}): string {
  const project = options.projectName ?? "this project";
  const wikiPath = options.wikiPath ?? ".kitsuden/brain";

  return `# BRAIN.md — Second Brain schema (${project})

> Karpathy-style configuration document. Any AI (local, API or CLI)
> that maintains this wiki MUST follow these rules. Automatically generated by
> KITSUDEN Brain — do not edit it by hand.

## The 3 layers

- **Layer 1 — \`sources\` (table \`brain_sources\`)**: raw and IMMUTABLE corpus.
  The AI reads but NEVER edits. Each source is identified by the SHA-256 hash of
  its content. Recapturing the same content is idempotent.
- **Layer 2 — \`wiki\` (table \`brain_notes\` + \`${wikiPath}/\`)**: maintained by AI.
  Summaries, concept pages and cross-references. You read; the AI writes.
- **Layer 3 — this \`BRAIN.md\`**: the schema. Structure, conventions and flows.

## Rules for wiki pages

- Required frontmatter: \`title\`, \`summary\`, \`source_path\`, \`tags\`, \`updated_at\`.
- Every page starts with a 2-3 sentence summary.
- Cross-link concepts with \`[[Title]]\` syntax.
- Cite the source by its \`source_path\` (\`source:<uuid>\`). NEVER invent data
  that is not in the raw source of Layer 1.
- A single source can touch 10-15 pages: propagate the backlinks.

## The 4 operations

| Operation | Deterministic | What it does |
| :-------- | :----------- | :------- |
| \`capture\` | core yes, prose depends on author | Ingests a source → derives its page → discovers connections. |
| \`sync\`    | yes | Reconciles Layer 2 from Layer 1 (creates missing pages). |
| \`lint\`    | **100% yes** | Health-check: broken links, orphans, stale, duplicates, thin pages. |
| \`digest\`  | selection yes, prose depends on author | Recap of recent activity. |

## Authors (how the prose is written)

The analysis (extractive summary, keywords, headings, backlinks) is DETERMINISTIC
and comes already solved (\`extraction.ts\`). The author only writes:

- \`instruction\` (default): zero AI, offline. Emits the page + a
  \`<!-- AGENT-TASK -->\` block with instructions so a LOCAL AI completes it.
- \`api\`: uses an LLM via API (Anthropic).
- \`cli\`: invokes a binary (\`claude -p\`, \`ollama run\`, ...) via stdin/stdout.

Select with the environment variable \`KITSUDEN_BRAIN_AUTHOR=instruction|api|cli\`.

## HTTP endpoints

\`\`\`
POST /api/brain/sources     # ingest raw source (Layer 1)
GET  /api/brain/sources     # list sources
POST /api/brain/capture     # ingest + derive page (Layer 1 → Layer 2)
POST /api/brain/sync        # reconcile Layer 2 from Layer 1
GET  /api/brain/lint        # deterministic health-check
POST /api/brain/digest      # recap of recent activity
GET  /api/brain/schema      # this BRAIN.md
\`\`\`

## Flow for a local AI

1. Read this BRAIN.md.
2. Run \`capture\` with the new source (or let the user upload it).
3. If the author was \`instruction\`, look for pages with an \`AGENT-TASK\` block and
   complete them following the rules above; remove the block when finished.
4. Run \`lint\` and fix what it reports (broken links, orphans, contradictions).
5. Weekly, run \`digest\` for the recap.
`;
}
