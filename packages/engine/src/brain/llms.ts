/**
 * KITSUDEN Brain — llms.txt Generator
 *
 * Builds a central `llms.txt` and a `.llms/` directory so AI assistants
 * (Cursor, Claude, etc.) understand the project without hallucinating.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { BrainNote, KnowledgeGraph } from "./types";

export interface LlmsGenerateOptions {
  projectRoot?: string;
  notes: BrainNote[];
  graph: KnowledgeGraph;
  projectName?: string;
}

interface LlmsSection {
  name: string;
  content: string;
}

function buildSections(notes: BrainNote[], graph: KnowledgeGraph): LlmsSection[] {
  const byCategory = new Map<string, BrainNote[]>();
  for (const note of notes) {
    const list = byCategory.get(note.category) ?? [];
    list.push(note);
    byCategory.set(note.category, list);
  }

  const sections: LlmsSection[] = [];

  // Overview
  sections.push({
    name: "overview",
    content: [
      "# KITSUDEN Project Overview",
      "",
      "KITSUDEN is a BaaS/CMS hybrid built on Bun + Hono + Drizzle ORM + PostgreSQL.",
      "This document is auto-generated by KITSUDEN Brain.",
      "",
      `## Stats`,
      `- Total notes: ${notes.length}`,
      `- Categories: ${Array.from(byCategory.keys()).join(", ")}`,
    ].join("\n"),
  });

  // Schema
  const schemaNotes = byCategory.get("schema") ?? [];
  sections.push({
    name: "schema",
    content: [
      "# Database Schema",
      "",
      ...schemaNotes.map((n) => `- ${n.title}: ${n.content.split("\n")[1] ?? ""}`),
    ].join("\n"),
  });

  // Routes
  const routeNotes = byCategory.get("route") ?? [];
  sections.push({
    name: "routes",
    content: ["# API Routes", "", ...routeNotes.map((n) => `- ${n.title}\n${n.content}`)].join(
      "\n"
    ),
  });

  // Kons
  const konNotes = byCategory.get("kon") ?? [];
  sections.push({
    name: "kons",
    content: [
      "# Kons (Modules)",
      "",
      ...konNotes.map((n) => `- ${n.title}: ${n.sourcePath ?? ""}`),
    ].join("\n"),
  });

  // Agents
  const agentNotes = byCategory.get("agent") ?? [];
  sections.push({
    name: "agents",
    content: ["# Agents", "", ...agentNotes.map((n) => `- ${n.title}\n${n.content}`)].join("\n"),
  });

  // Knowledge Graph
  sections.push({
    name: "graph",
    content: [
      "# Knowledge Graph",
      "",
      "## Nodes",
      ...graph.nodes.map((n) => `- [${n.type}] ${n.label} (${n.id})`),
      "",
      "## Edges",
      ...graph.edges.map(
        (e) => `- ${e.source} --[${e.relation}, ${e.strength.toFixed(2)}]--> ${e.target}`
      ),
    ].join("\n"),
  });

  return sections;
}

/**
 * Generate `llms.txt` and `.llms/*.md` files.
 */
export function generateLlms(options: LlmsGenerateOptions): { files: string[] } {
  const root = options.projectRoot ?? ".";
  const llmsDir = join(root, ".llms");
  if (!existsSync(llmsDir)) {
    mkdirSync(llmsDir, { recursive: true });
  }

  const sections = buildSections(options.notes, options.graph);
  const files: string[] = [];

  // Write .llms/*.md
  for (const section of sections) {
    const filePath = join(llmsDir, `${section.name}.md`);
    writeFileSync(filePath, section.content);
    files.push(filePath);
  }

  // Write root llms.txt
  const summary = [
    `# ${options.projectName ?? "KITSUDEN Project"}`,
    "",
    "> Auto-generated by KITSUDEN Brain. Feed this file to your AI assistant.",
    "",
    // This file is about the CODEBASE. It is served at /api/brain/llms.txt and was
    // being mistaken for the API guide: say where that one lives.
    "> This file describes the Kitsuden codebase. To build ON a running Kitsuden, read `GET /llms.txt` from its API (live routes, rules, recipes) and use the MCP domain tools: tournament_*, tierlist_*, catalog_*, broadcast_*.",
    "",
    "## Sections",
    "",
    ...sections.map((s) => `- [${s.name}](.llms/${s.name}.md)`),
    "",
    "## Quick Reference",
    "",
    `- Runtime: Bun`,
    `- Router: Hono`,
    `- ORM: Drizzle ORM`,
    `- Database: PostgreSQL`,
    `- Total documented entities: ${options.notes.length}`,
    `- Knowledge graph: ${options.graph.nodes.length} nodes, ${options.graph.edges.length} edges`,
    "",
    "## Rules for AI Assistants",
    "",
    "1. Prefer existing tables in `apps/api/src/db/schema-core.ts` before creating new ones.",
    "2. Add new routes in `apps/api/src/routes/` and mount them in `apps/api/src/index.ts`.",
    "3. Business logic belongs in `packages/kons/`, not in core engine code.",
    "4. Use the Brain Knowledge Graph to understand relationships between entities.",
  ].join("\n");

  const llmsTxtPath = join(root, "llms.txt");
  writeFileSync(llmsTxtPath, summary);
  files.push(llmsTxtPath);

  return { files };
}
