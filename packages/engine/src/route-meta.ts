/**
 * Route metadata — what a route can say about itself
 * ============================================================================
 *
 * ── THE PROBLEM ────────────────────────────────────────────────────────────
 *
 * Kitsuden's OpenAPI only published what each kon declared BY HAND in
 * `openApi.paths`. No kon declared it. Measured against a running
 * installation, `GET /api/docs/openapi.json` documented 15 operations: the generic CRUD
 * of `/items` and two test datasets. Not a single route for tournaments, tier
 * lists or broadcast — while 62 kon routes validated their body with zod.
 *
 * So the schema existed and nobody read it, and a vibecoder who generated
 * the SDK received a client with nothing from the domain. Their agent ended up writing
 * rows by hand to `/items/esports_matches`, skipping precisely the rules that are
 * the product's value.
 *
 * ── THE SOLUTION ───────────────────────────────────────────────────────────
 *
 * Declaring by hand is the option that already failed, so the route DESCRIBES ITSELF:
 * each middleware that knows something about the route leaves it written on its own
 * function —`validateRequest` its schema, `requireAuth` that it requires a session, the
 * section guard which section it requires— and the API walks the mounted routes of
 * each kon to build the contract.
 *
 * A new route appears in the OpenAPI without anyone having to remember anything. Which is the
 * only way for a contract not to fall behind.
 */

import type { MiddlewareHandler } from "hono";

/**
 * Key shared via `Symbol.for`, not `Symbol()`: if two copies of the
 * engine end up loaded —a kon with its own `node_modules`— they must
 * recognize each other's metadata.
 */
export const ROUTE_META = Symbol.for("kitsuden.route.meta");

export interface RouteValidationMeta {
  target: "json" | "query" | "param" | "form";
  /** Zod schema. Typed as `unknown` so as not to tie this module to zod. */
  schema: unknown;
}

export interface RouteMeta {
  summary?: string;
  description?: string;
  operationId?: string;
  tags?: string[];
  /** `required`: without a credential it responds 401. `optional`: uses it if it arrives. */
  auth?: "required" | "optional";
  /** Section of a kon that must be switched on (see kon-broadcast). */
  section?: string;
  validation?: RouteValidationMeta[];
  /**
   * The route was generated by the kon SDK from this declaration: OpenAPI
   * and MCP come out of it (output schemas, scope, errors…), not from what
   * can be deduced from the middlewares. Typed as `unknown` so as not to tie
   * this module to `@kitsuden/shared`.
   */
  operation?: { konId: string; declaration: unknown };
}

type WithMeta = { [ROUTE_META]?: RouteMeta };

/**
 * Hono WRAPS the handler when mounting a sub-router that has its own
 * `onError`, and stores the original in this property. Without following it, the
 * metadata of those routers would be invisible and their routes would come out without a schema.
 */
const COMPOSED_HANDLER = "__COMPOSED_HANDLER";

/** Attaches metadata to a function (middleware or handler) and returns it. */
export function withRouteMeta<T extends object>(fn: T, meta: RouteMeta): T {
  const prior = (fn as WithMeta)[ROUTE_META];
  const combined: RouteMeta = {
    ...prior,
    ...meta,
    validation: [...(prior?.validation ?? []), ...(meta.validation ?? [])],
  };
  Object.defineProperty(fn, ROUTE_META, {
    value: combined,
    configurable: true,
    enumerable: false,
    writable: true,
  });
  return fn;
}

/**
 * Middleware that does nothing except describe the route.
 *
 *     app.post("/tournament/:id/report", describeRoute({ summary: "…" }), …)
 *
 * For what no other middleware knows: the human summary and a readable
 * `operationId`, which ends up being the method name in
 * the generated SDK.
 */
export function describeRoute(meta: Omit<RouteMeta, "validation">): MiddlewareHandler {
  const mw: MiddlewareHandler = async (_c, next) => {
    await next();
  };
  return withRouteMeta(mw, meta);
}

/** Reads the metadata of a function, going through Hono's wrappers. */
export function readRouteMeta(fn: unknown): RouteMeta | undefined {
  let actual = fn as (WithMeta & Record<string, unknown>) | undefined;
  for (let i = 0; i < 5 && actual; i++) {
    const meta = actual[ROUTE_META];
    if (meta) return meta;
    actual = actual[COMPOSED_HANDLER] as typeof actual;
  }
  return undefined;
}
