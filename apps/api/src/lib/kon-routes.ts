/**
 * Kon route registry — the contract comes from what is mounted
 * ============================================================================
 *
 * ── WHY IT EXISTS ──────────────────────────────────────────────────────────
 *
 * The OpenAPI only included what a kon declared by hand in `openApi.paths`, and
 * no kon did: the published contract had zero domain routes
 * while the API served more than a hundred. Asking each kon to maintain a
 * parallel list is exactly what already did not work.
 *
 * Here the REAL router of each kon is stored at the moment it is mounted, and everything is derived from its
 * routes: method, path, whether it requires a credential, which section it needs
 * and the body schema. What is mounted is what is documented — by
 * construction, not by discipline.
 *
 * ── WHERE EACH PIECE OF DATA COMES FROM ────────────────────────────────────
 *
 * Hono keeps in `router.routes` one entry per registered function: a
 * route with three middlewares is three entries with the same method and path. Those
 * from `app.use()` carry method `ALL`. Each middleware that knows something leaves it in
 * its metadata (`withRouteMeta` in `@kitsuden/engine`), and they are joined here.
 *
 * An honest limitation: a hand-written middleware without metadata —such as the
 * one that exempts the local agent push in Broadcast— is not seen. The route is
 * documented all the same, but not marked as protected.
 */

// From the module and not from the engine index: see the cycle explained
// in `middleware/auth.ts`. This file is imported by the kon loader.
import {
  readRouteMeta,
  type RouteMeta,
  type RouteValidationMeta,
} from "@kitsuden/engine/src/route-meta";

export interface KonRoute {
  konId: string;
  /** Uppercase: `GET`, `POST`… */
  method: string;
  /** Full path as Hono serves it: `/api/esports/tournaments/:id`. */
  path: string;
  /** Relative to the kon's mount: `/tournaments/:id`. */
  relativePath: string;
  mountPath: string;
  auth: "required" | "optional" | "none";
  section?: string;
  summary?: string;
  description?: string;
  operationId?: string;
  tags?: string[];
  validation: RouteValidationMeta[];
  /** If generated by the kons SDK: its declaration (see `RouteMeta.operation`). */
  operation?: { konId: string; declaration: unknown };
}

interface MountedRouter {
  konId: string;
  mountPath: string;
  router: { routes: { method: string; path: string; handler: unknown }[] };
}

const registry = new Map<string, MountedRouter>();

/** Called by the kon loader right after `app.route(mountPath, router)`. */
export function registerKonRouter(konId: string, mountPath: string, router: unknown): void {
  const routes = (router as { routes?: unknown })?.routes;
  if (!Array.isArray(routes)) return;
  registry.set(konId, {
    konId,
    mountPath: mountPath.replace(/\/+$/, ""),
    router: router as MountedRouter["router"],
  });
}

/**
 * The mounted kon that serves this path (the one with the longest mount that covers it),
 * or `null`. Used by agent denials on legacy routes.
 */
export function pathKon(path: string): string | null {
  let best: { konId: string; length: number } | null = null;
  for (const { konId, mountPath } of registry.values()) {
    if (!mountPath || mountPath === "/api") continue;
    if (path === mountPath || path.startsWith(`${mountPath}/`)) {
      if (!best || mountPath.length > best.length) best = { konId, length: mountPath.length };
    }
  }
  return best?.konId ?? null;
}

/** The mounted kons with their prefix (for the panel's permission catalog). */
export function mountedKons(): { konId: string; mountPath: string }[] {
  return [...registry.values()].map(({ konId, mountPath }) => ({ konId, mountPath }));
}

/** For tests. */
export function forgetKonRouters(): void {
  registry.clear();
}

/** Does the pattern of an `app.use()` cover this path? */
function patternCovers(pattern: string, path: string): boolean {
  if (pattern === "*" || pattern === "/*") return true;
  if (pattern.endsWith("/*")) {
    const base = pattern.slice(0, -2);
    return path === base || path.startsWith(`${base}/`);
  }
  return pattern === path;
}

function join(mountPath: string, relativeValue: string): string {
  if (relativeValue === "/" || relativeValue === "") return mountPath || "/";
  return `${mountPath}${relativeValue.startsWith("/") ? "" : "/"}${relativeValue}`;
}

/** All routes of all mounted kons, with their metadata already joined. */
export function konRoutes(): KonRoute[] {
  const output: KonRoute[] = [];

  for (const { konId, mountPath, router } of registry.values()) {
    const middlewares = router.routes.filter((r) => r.method.toUpperCase() === "ALL");
    const groups = new Map<string, { method: string; path: string; handlers: unknown[] }>();

    for (const r of router.routes) {
      const method = r.method.toUpperCase();
      if (method === "ALL") continue;
      const key = `${method} ${r.path}`;
      const group = groups.get(key) ?? { method, path: r.path, handlers: [] };
      group.handlers.push(r.handler);
      groups.set(key, group);
    }

    for (const group of groups.values()) {
      const ownItems = group.handlers.map(readRouteMeta).filter(Boolean) as RouteMeta[];
      const inherited = middlewares
        .filter((m) => patternCovers(m.path, group.path))
        .map((m) => readRouteMeta(m.handler))
        .filter(Boolean) as RouteMeta[];
      const all = [...inherited, ...ownItems];

      const auth = all.some((m) => m.auth === "required")
        ? "required"
        : all.some((m) => m.auth === "optional")
          ? "optional"
          : "none";

      const described = ownItems.find((m) => m.summary || m.operationId || m.description);

      output.push({
        konId,
        method: group.method,
        path: join(mountPath, group.path),
        relativePath: group.path,
        mountPath,
        auth,
        section: all.find((m) => m.section)?.section,
        summary: described?.summary,
        description: described?.description,
        operationId: described?.operationId,
        tags: described?.tags,
        validation: all.flatMap((m) => m.validation ?? []),
        operation: ownItems.find((m) => m.operation)?.operation,
      });
    }
  }

  return output.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

// ── Suggestions for a 404 ────────────────────────────────────────────────────
//
// The `/api/*` 404 is anonymous and the caller writes the path: up to ~16 KB.
// A full edit distance against every route was O(routes × length²) on the
// single thread (security review F3/F8). Now: a length cap, a filter by length
// and segment count, a banded distance with early exit, and the templates
// compiled only once.

/** Above this length nothing is suggested: no real path looks like that. */
export const MAX_LENGTH_TO_SUGGEST = 200;
/** Nor is `Allow` computed: past this, the path belongs to no route. */
export const MAX_LENGTH_FOR_ALLOW = 2000;
/** Maximum distance to suggest (and width of the distance band). */
const MAX_THRESHOLD = 20;

/**
 * Levenshtein distance if it is `<= cap`; otherwise `cap + 1`. Only computes
 * the band of width `2·cap + 1` around the diagonal and stops as soon as a
 * whole row exceeds the cap: O(length × cap), not O(length²).
 */
export function boundedDistance(a: string, b: string, cap: number): number {
  if (Math.abs(a.length - b.length) > cap) return cap + 1;
  if (a === b) return 0;
  // A common prefix and suffix cost nothing: with the template parameter
  // filled from the requested path, most of the text is shared and the
  // table shrinks to almost nothing.
  let start = 0;
  while (start < a.length && start < b.length && a.charCodeAt(start) === b.charCodeAt(start))
    start++;
  let endA = a.length;
  let endB = b.length;
  while (endA > start && endB > start && a.charCodeAt(endA - 1) === b.charCodeAt(endB - 1)) {
    endA--;
    endB--;
  }
  if (start > 0 || endA < a.length) {
    a = a.slice(start, endA);
    b = b.slice(start, endB);
  }
  if (a.length === 0 || b.length === 0) {
    const d = Math.max(a.length, b.length);
    return d <= cap ? d : cap + 1;
  }
  const out = cap + 1;
  let previous = new Array<number>(b.length + 1).fill(out);
  let current = new Array<number>(b.length + 1).fill(out);
  for (let j = 0; j <= Math.min(b.length, cap); j++) previous[j] = j;
  for (let i = 1; i <= a.length; i++) {
    const from = Math.max(1, i - cap);
    const to = Math.min(b.length, i + cap);
    // Only the band and its two edges (`out` sentinels) are touched: what
    // lies outside the band is never read.
    current[0] = i <= cap ? i : out;
    if (from > 1) current[from - 1] = out;
    if (to < b.length) current[to + 1] = out;
    let minimum = current[0];
    for (let j = from; j <= to; j++) {
      const cost = a.charCodeAt(i - 1) === b.charCodeAt(j - 1) ? 0 : 1;
      const v = Math.min(previous[j]! + 1, current[j - 1]! + 1, previous[j - 1]! + cost);
      current[j] = v > out ? out : v;
      if (current[j]! < minimum) minimum = current[j]!;
    }
    if (minimum > cap) return out;
    [previous, current] = [current, previous];
  }
  return Math.min(previous[b.length]!, out);
}

function templateRegex(template: string): RegExp {
  const regex = template
    .split("/")
    .map((seg) =>
      seg.startsWith(":") ? "[^/]+" : seg === "*" ? ".*" : seg.replace(/[.+?^${}()|[\]\\]/g, "\\$&")
    )
    .join("/");
  return new RegExp(`^${regex}/?$`);
}

interface SuggestableRoute {
  method: string;
  path: string;
  segments: string[];
  regex: RegExp;
}

/**
 * The routes already split and with their compiled regex, recomputed only
 * when what is mounted changes (fingerprint: kons and route count of each router).
 */
let suggestionIndex: { fingerprint: string; routes: SuggestableRoute[] } | null = null;

function suggestableRoutes(): SuggestableRoute[] {
  const fingerprint = [...registry.values()]
    .map((r) => `${r.konId}:${r.mountPath}:${r.router.routes.length}`)
    .join("|");
  if (suggestionIndex?.fingerprint === fingerprint) return suggestionIndex.routes;
  const routes = konRoutes().map((r) => ({
    method: r.method,
    path: r.path,
    segments: r.path.split("/"),
    regex: templateRegex(r.path),
  }));
  suggestionIndex = { fingerprint, routes };
  return routes;
}

/**
 * Capped distance between a template and the requested path.
 *
 * With the same number of segments, they are compared segment by segment and
 * the parameters take what was requested: in `/tournament/abc/reports` against
 * `/tournament/:id/report` the difference is an `s`, not the id. A parameter
 * costs 0 however long it is, and a short literal against a long segment is
 * discarded by length at once. With a different number of segments the whole
 * template is compared.
 */
function distanceToRoute(
  r: SuggestableRoute,
  clean: string,
  segments: string[],
  cap: number
): number {
  if (r.segments.length !== segments.length) return boundedDistance(r.path, clean, cap);
  let total = 0;
  for (let i = 0; i < segments.length; i++) {
    const seg = r.segments[i]!;
    if (seg.startsWith(":")) continue;
    total += boundedDistance(seg, segments[i]!, cap - total);
    if (total > cap) return cap + 1;
  }
  return total;
}

/**
 * Per-client suggestion budget.
 *
 * The general limiter counts per path, and every junk path starts its own
 * counter: a client that makes up routes never exhausts it (security review
 * F3/F8). This counts per client. Past the budget the 404 still answers, only
 * without computing suggestions, which is what costs CPU.
 */
export const SUGGESTIONS_PER_MINUTE = 60;
const SUGGESTION_WINDOW_MS = 60_000;
// Memory ceiling: with more distinct clients than this, start from scratch.
const MAX_TRACKED_CLIENTS = 10_000;
const suggestionSpend = new Map<string, { since: number; used: number }>();

export function canSuggest(client: string, now = Date.now()): boolean {
  const spend = suggestionSpend.get(client);
  if (!spend || now - spend.since >= SUGGESTION_WINDOW_MS) {
    if (!spend && suggestionSpend.size >= MAX_TRACKED_CLIENTS) suggestionSpend.clear();
    suggestionSpend.set(client, { since: now, used: 1 });
    return true;
  }
  spend.used++;
  return spend.used <= SUGGESTIONS_PER_MINUTE;
}

/** For tests. */
export function forgetSuggestionSpend(): void {
  suggestionSpend.clear();
}

export interface RouteSuggestion {
  /** Methods this same path DOES exist with. Empty if it does not exist. */
  allow: string[];
  /** Similar routes, the most similar first. */
  didYouMean: { method: string; path: string }[];
}

/**
 * What to say when nothing matches.
 *
 * A bare 404 is the worst possible error for an agent: it does not tell apart "you got the
 * method wrong" from "you got the path wrong" from "that route does not
 * exist". Here all three are answered.
 */
export function suggestRoutes(method: string, pathValue: string, max = 3): RouteSuggestion {
  if (pathValue.length > MAX_LENGTH_FOR_ALLOW) return { allow: [], didYouMean: [] };
  const routes = suggestableRoutes();

  const allow = [
    ...new Set(routes.filter((r) => r.regex.test(pathValue)).map((r) => r.method)),
  ].sort();
  if (pathValue.length > MAX_LENGTH_TO_SUGGEST) return { allow, didYouMean: [] };

  let end = pathValue.length;
  while (end > 1 && pathValue[end - 1] === "/") end--;
  const clean = pathValue.slice(0, end) || "/";
  // More than ~20 edits is no longer "a typo": the ceiling also bounds the band.
  const threshold = Math.min(MAX_THRESHOLD, Math.max(3, Math.floor(clean.length * 0.25)));
  const segments = clean.split("/");
  const wanted = method.toUpperCase();

  const candidates: { method: string; path: string; d: number }[] = [];
  for (const r of routes) {
    // Each extra or missing segment costs at least one character (the `/`).
    if (Math.abs(r.segments.length - segments.length) > threshold) continue;
    const d = distanceToRoute(r, clean, segments, threshold);
    if (d > threshold) continue;
    // Same method, with equal path, goes first.
    candidates.push({ method: r.method, path: r.path, d: d + (r.method === wanted ? 0 : 0.5) });
  }

  const didYouMean = candidates
    .filter((r) => r.d <= threshold)
    .sort((a, b) => a.d - b.d)
    .slice(0, max)
    .map(({ method: m, path }) => ({ method: m, path }));

  return { allow, didYouMean };
}
