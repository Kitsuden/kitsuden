/**
 * ═══════════════════════════════════════════════════════════════════════════
 * NATIVE POSTGRESQL RLS - The Titanium Wall (AI-Ready Phase)
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * This middleware implements the "second line of defense" against data leaks
 * through PostgreSQL's native Row Level Security (RLS).
 *
 * HYBRID SECURITY ARCHITECTURE:
 *
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ LEVEL 1 (App): RLS via Drizzle WHERE                                  │
 * │   → Optimal performance, filters in SQL                               │
 * │   → Implemented in: lib/rls-builder.ts                                │
 * ├─────────────────────────────────────────────────────────────────────────┤
 * │ LEVEL 2 (DB): Native PostgreSQL RLS  ← THIS FILE                      │
 * │   → Absolute security, cannot be bypassed                             │
 * │   → Protects against:                                                 │
 * │     • Bugs in the application code                                    │
 * │     • SQL queries generated by AI (MCP Server)                        │
 * │     • Direct access to the database                                   │
 * └─────────────────────────────────────────────────────────────────────────┘
 *
 * HOW IT WORKS:
 * 1. Each HTTP request is wrapped in a PostgreSQL transaction
 * 2. The user_id is injected into the session variable `app.current_user_id`
 * 3. PostgreSQL evaluates the RLS policies on EVERY query automatically
 * 4. If a query tries to access another user's data, PostgreSQL rejects it
 *
 * RLS POLICIES (defined in db/rls-policies.sql):
 * - data_entries_owner_isolation: Only the owner can view/modify their data
 * - data_entries_public_read: Public records visible to everyone
 *
 * USAGE EXAMPLE:
 * ```typescript
 * const app = new Hono()
 *   .use(withTransactionalRLS())  // ← Activates the Titanium Wall
 *   .get("/api/datasets/:id/entries", async (c) => {
 *     // PostgreSQL automatically filters only the allowed records
 *     const entries = await c.get("tx").select().from(dataEntries);
 *     return c.json(entries);
 *   });
 * ```
 *
 * NOTE ON MCP SERVER:
 * When the MCP (Model Context Protocol) server generates SQL queries,
 * native RLS guarantees that:
 * - A normal user will NEVER see other users' data
 * - Only admins can see all records
 * - Even if the AI "hallucinates" and generates SELECT * FROM data_entries,
 *   PostgreSQL will only return the records allowed by the policies.
 *
 * @module middleware/transactional-rls
 * @see db/rls-policies.sql - RLS policy definition
 * @see lib/rls-builder.ts - Level 1 (Drizzle WHERE)
 * @see https://www.postgresql.org/docs/current/ddl-rowsecurity.html
 */

