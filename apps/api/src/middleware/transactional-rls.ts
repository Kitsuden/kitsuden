/**
 * Hono middleware that wraps each request in a PostgreSQL transaction
 * with the RLS context injected.
 *
 * This is the "Titanium Wall" - it guarantees that even if the application
 * code has bugs or the AI generates incorrect queries, PostgreSQL
 * will never allow seeing other users' data.
 *
 * FEATURES:
 * - ✅ Automatically injects the session's user_id
 * - ✅ Rolls back automatically if an error occurs
 * - ✅ Exposes `c.get("tx")` to use the transaction in handlers
 * - ✅ Security logs in debug mode
 * - ✅ Compatible with Better-Auth
 *
 * BASIC USAGE:
 * ```typescript
 * import { Hono } from "hono";
 * import { withTransactionalRLS } from "./middleware/transactional-rls";
 *
 * const app = new Hono();
 * app.use(withTransactionalRLS());
 *
 * app.get("/entries", async (c) => {
 *   const tx = c.get("tx");
 *   const entries = await tx.select().from(dataEntries);
 *   return c.json(entries);
 * });
 * ```
 *
 * ADVANCED USAGE (with Better-Auth):
 * ```typescript
 * app.use("/api/*", getSession).use(withTransactionalRLS());
 * ```
 *
 * @returns Hono middleware
 */
export function withTransactionalRLS() {
  // The transaction, the context, idempotency (no nesting), the request scope
  // and the rollback if the route fails live in the engine (`rlsTransaction`),
  // shared with the kons. Here only what is the core's own: `c.get("tx")`,
  // `rlsUser` and the log. The log goes through the logger and NOT `console.log`: it runs
  // on EVERY request and a stray line would come out without `trace_id`.
  return rlsTransaction(() => db, {
    onOpen(c, tx, { userId, userRole }) {
      c.set("tx", tx);
      c.set("rlsUser", { id: userId || null, role: userRole });
      logger.debug({ userId: userId || null, userRole }, "[RLS] transaction opened");
    },
    // A caught and swallowed SQL error left the transaction aborted and
    // Postgres rolled back the whole request. It is a route bug (it is missing a
    // `withSavepoint`/`attemptSql`): let it show in the log with its route.
    onLosingConfirmation(_c, info) {
      logger.error(
        {
          method: info.method,
          path: info.route,
          status: info.status,
          sqlCode: info.error?.code,
          sqlError: info.error?.message,
          responseReplaced: info.changedResponse,
        },
        "[RLS] the request's transaction ended up aborted: nothing was saved"
      );
    },
  });
}

/**
 * Helper to run code with RLS context in a non-HTTP context.
 *
 * Useful for background jobs, cron tasks, or code that has no access
 * to the Hono context.
 *
 * @param user - User for the RLS context
 * @param fn - Function to run with the RLS context
 * @returns Result of the function
 *
 * @example
 * ```typescript
 * const result = await withRLSContext(
 *   { id: "system", role: "admin" },
 *   async (tx) => {
 *     return await tx.select().from(dataEntries);
 *   }
 * );
 * ```
 */
export async function withRLSContext<T>(
  user: RLSUser | null,
  fn: (tx: TransactionType) => Promise<T>
): Promise<T> {
  return await db.transaction(async (tx) => {
    await setRLSContext(tx, user);
    return await fn(tx);
  });
}

