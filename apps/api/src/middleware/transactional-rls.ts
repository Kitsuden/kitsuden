/**
 * User object from Better-Auth session
 */
export interface RLSUser {
  id: string;
  email?: string;
  role?: "admin" | "editor" | "user";
}

/**
 * RLS context injected into the transaction
 */
export interface RLSContext {
  userId: string | null;
  userRole: string | null;
  isAdmin: boolean;
}

/**
 * Type for a Drizzle transaction
 */
type TransactionType = DatabaseTransaction;

// ═══════════════════════════════════════════════════════════════════════════
// UTILITIES
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Sets the RLS context in the PostgreSQL session.
 *
 * This function injects the session variables that the RLS policies
 * will use to evaluate access to the data.
 *
 * @param tx - Drizzle transaction
 * @param user - Authenticated user or null for anonymous
 *
 * @example
 * ```typescript
 * await db.transaction(async (tx) => {
 *   await setRLSContext(tx, { id: "user-123", role: "user" });
 *   // Now all queries will use this RLS context
 * });
 * ```
 */
export async function setRLSContext(tx: TransactionType, user: RLSUser | null): Promise<void> {
  /**
   * `is_local = true` (in `setRlsContext`): the value lives as long as the
   * transaction does and Postgres undoes it by itself when it ends. With `false` the value
   * stayed in the SESSION —a pool connection that is lent to different
   * people— and the next request that touched it without passing through here inherited
   * the previous user.
   */
  await setRlsContext(tx, user);
}

/**
 * Which id and which role Postgres sees for a user (or for nobody): the rule lives
 * in the engine (`rlsContextOf`), shared with the kons.
 *
 * · Without a user: id '' and role `anonymous` —it is NOT the system, which is id AND role
 *   empty—.
 * · With a user and no role: `user` (it used to fall into `anonymous`).
 */
export const contextOf = rlsContextOf;

/** As the system inside the request's transaction (see the engine). */
export { asSystem };

/**
 * Clears the RLS context at the end of the transaction.
 *
 * Although it is not strictly necessary (PostgreSQL clears it when the
 * connection closes), it is good security practice.
 *
 * @param tx - Drizzle transaction
 */
export async function clearRLSContext(tx: TransactionType): Promise<void> {
  // Local, as when it was set: otherwise "clearing" would leave the connection marked as
  // anonymous for whoever uses it next, which is the same failure in reverse.
  await tx.execute(sql`SELECT set_config('app.current_user_id', '', true)`);
  await tx.execute(sql`SELECT set_config('app.current_user_role', '', true)`);
}

/**
 * Gets the current RLS context from the PostgreSQL session.
 * Useful for debugging and logging.
 *
 * @param tx - Drizzle transaction
 * @returns Current RLS context
 */
export async function getRLSContext(tx: TransactionType): Promise<RLSContext> {
  const [userIdResult, userRoleResult] = await Promise.all([
    tx.execute(sql`SELECT current_setting('app.current_user_id', true)`) as Promise<{
      rows: { current_setting: string }[];
    }>,
    tx.execute(sql`SELECT current_setting('app.current_user_role', true)`) as Promise<{
      rows: { current_setting: string }[];
    }>,
  ]);

  const userId = userIdResult.rows[0]?.current_setting || null;
  const userRole = userRoleResult.rows[0]?.current_setting || null;

  return {
    userId,
    userRole,
    isAdmin: userRole === "admin",
  };
}

