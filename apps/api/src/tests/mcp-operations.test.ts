/**
 * MCP: the kon SDK's operations as tools, with real scopes
 * ============================================================================
 *
 * Against the REAL app (test Postgres, kons loaded): real agents
 * (`createAgent`) open an MCP session, list tools and call the
 * GENERATED ones of `kon-blocks` (the page builder):
 *
 *   · an agent with `content:edit` sees and executes `blocks__create-page`;
 *     repeating the call with the same `idempotency_key` returns the first
 *     result without creating another page;
 *   · one without that scope sees the read tools but not the write ones, and if it calls
 *     a write one it gets KITSUDEN_E_FORBIDDEN;
 *   · `allowedTools` trims what the session sees and can call;
 *   · an argument that does not exist is KITSUDEN_E_VALIDATION with the valid ones.
 */

import { describe, it, expect, beforeAll, afterAll } from "bun:test";

import { installedKon } from "../lib/installed-kons";

// The guide and the audit are tested with the SDK's pilot kon, kon-blog, which is
// INSTALLABLE (kitsuden-kons): without it, they are skipped.
const itWithBlog = installedKon("kon-blog")?.path ? it : it.skip;
import { and, eq } from "drizzle-orm";

import { db } from "../db";
import { agentAuditLogs } from "../db/schema";
import { app } from "../index";
import { createAgent } from "../services/agent-auth";

import { isDatabaseAvailable, generateTestId } from "./setup";

let dbAvailable = false;

interface Session {
  agentId: string;
  token: string;
  sessionId: string;
  close: () => Promise<void>;
}

const open: Session[] = [];

async function mcpSession(scopes: string[], allowedTools: string[] = []): Promise<Session> {
  const { agent, plainApiKey } = await createAgent({
    name: `mcp-ops-${scopes.join("+")}-${generateTestId()}`,
    scopes,
    allowedTools,
    rateLimit: 100_000,
  });
  const res = await app.request(
    new Request("http://localhost:3000/api/mcp", {
      headers: { Authorization: `Bearer ${plainApiKey}` },
    })
  );
  expect(res.status).toBe(200);
  const reader = res.body!.getReader();
  let text = "";
  while (!text.includes("\n\n")) {
    const { value, done } = await reader.read();
    if (done) break;
    text += new TextDecoder().decode(value);
  }
  const sessionId = text.match(/sessionId=([a-zA-Z0-9-]+)/)![1]!;
  const s: Session = {
    agentId: agent.id,
    token: plainApiKey,
    sessionId,
    close: () => reader.cancel().catch(() => {}),
  };
  open.push(s);
  return s;
}

let nextId = 1;
// eslint-disable-next-line @typescript-eslint/no-explicit-any -- JSON-RPC response read in the test
async function rpc(s: Session, method: string, params: unknown): Promise<any> {
  const res = await app.request(
    new Request(`http://localhost:3000/api/mcp?sessionId=${s.sessionId}`, {
      method: "POST",
      headers: { Authorization: `Bearer ${s.token}`, "Content-Type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: nextId++, method, params }),
    })
  );
  expect(res.status).toBe(200);
  return res.json();
}

async function toolsValue(s: Session): Promise<string[]> {
  const r = await rpc(s, "tools/list", {});
  return (r.result.tools as { name: string }[]).map((t) => t.name);
}

describe("MCP: tools generated by the kon SDK", () => {
  beforeAll(async () => {
    dbAvailable = await isDatabaseAvailable();
  });
  afterAll(async () => {
    for (const s of open) await s.close();
  });

  it("tools/list: the content editor sees write tools; the one without the scope, read only", async () => {
    if (!dbAvailable) return;
    const editor = await mcpSession(["mcp:connect", "content:edit"]);
    const reader = await mcpSession(["mcp:connect"]);

    const ofTheEditor = await toolsValue(editor);
    expect(ofTheEditor).toContain("blocks__create-page");
    expect(ofTheEditor).toContain("blocks__block-types");

    const ofTheReader = await toolsValue(reader);
    expect(ofTheReader).toContain("blocks__block-types");
    expect(ofTheReader).not.toContain("blocks__create-page");

    // The same schema as the REST route: the body, entirely under `body`
    const r = await rpc(editor, "tools/list", {});
    const create = (
      r.result.tools as { name: string; inputSchema: Record<string, unknown> }[]
    ).find((t) => t.name === "blocks__create-page")!;
    expect(Object.keys(create.inputSchema.properties as object)).toEqual(
      expect.arrayContaining(["body", "idempotency_key"])
    );
  });

  it("tools/call with scope: executes the operation (and A1's idempotency protects it)", async () => {
    if (!dbAvailable) return;
    const editor = await mcpSession(["mcp:connect", "content:edit"]);
    const slug = `mcp-${generateTestId()}`.toLowerCase().replace(/[^a-z0-9-]/g, "-");
    const args = {
      body: { title: "Created via MCP", slug },
      idempotency_key: `mcp-${generateTestId()}`,
    };

    const r1 = await rpc(editor, "tools/call", { name: "blocks__create-page", arguments: args });
    expect(r1.result.isError, JSON.stringify(r1.result).slice(0, 500)).toBeUndefined();
    expect(r1.result.structuredContent.status).toBe(201);
    expect(r1.result.structuredContent.data.slug).toBe(slug);

    const r2 = await rpc(editor, "tools/call", { name: "blocks__create-page", arguments: args });
    expect(r2.result.structuredContent.idempotentReplayed).toBe(true);
    expect(r2.result.structuredContent.data.id).toBe(r1.result.structuredContent.data.id);

    const { pages } = await import("../../../../packages/core/blocks/blocks.schema");
    const rows = await db.select({ id: pages.id }).from(pages).where(eq(pages.slug, slug));
    expect(rows.length).toBe(1);

    // And the generated read too
    const types = await rpc(editor, "tools/call", { name: "blocks__block-types", arguments: {} });
    expect(types.result.structuredContent.data.blockTypes.length).toBeGreaterThan(5);
  });

  it("tools/call WITHOUT the scope: KITSUDEN_E_FORBIDDEN and nothing is created", async () => {
    if (!dbAvailable) return;
    const reader = await mcpSession(["mcp:connect"]);
    const slug = `mcp-no-${generateTestId()}`.toLowerCase().replace(/[^a-z0-9-]/g, "-");

    const r = await rpc(reader, "tools/call", {
      name: "blocks__create-page",
      arguments: { body: { title: "Must not exist", slug } },
    });
    expect(r.result.isError).toBe(true);
    expect(r.result.structuredContent.code).toBe("KITSUDEN_E_FORBIDDEN");
    expect(r.result.structuredContent.status).toBe(403);

    const { pages } = await import("../../../../packages/core/blocks/blocks.schema");
    expect((await db.select({ id: pages.id }).from(pages).where(eq(pages.slug, slug))).length).toBe(
      0
    );
  });

  it("allowedTools trims what the session sees and what it can call", async () => {
    if (!dbAvailable) return;
    const trimmed = await mcpSession(["mcp:connect", "content:edit"], ["blocks__block-types"]);
    const list = await toolsValue(trimmed);
    expect(list).toContain("blocks__block-types");
    expect(list).not.toContain("blocks__create-page");

    const r = await rpc(trimmed, "tools/call", {
      name: "blocks__create-page",
      arguments: { body: { title: "x" } },
    });
    // The `allowedTools` gate is the usual one from routes/mcp.ts: JSON-RPC error
    expect(r.error.code).toBe(-32602);
    expect(r.error.data.code).toBe("KITSUDEN_E_FORBIDDEN");
  });

  it("an argument that does not exist: KITSUDEN_E_VALIDATION with the valid ones", async () => {
    if (!dbAvailable) return;
    const editor = await mcpSession(["mcp:connect", "content:edit"]);
    const r = await rpc(editor, "tools/call", {
      name: "blocks__create-page",
      arguments: { title: "the body goes in body" },
    });
    expect(r.result.isError).toBe(true);
    expect(r.result.structuredContent.code).toBe("KITSUDEN_E_VALIDATION");
    expect(JSON.stringify(r.result.structuredContent)).toContain("body");
  });
});

/**
 * Per-operation guide (the SDK's `guide`) and audit of each `tools/call`:
 *
 *   · whoever sees `blog__create-post` also sees its guide as the resource
 *     `kitsuden://guide/blog__create-post`, and reads it in markdown;
 *   · whoever does not see it does not have the resource (it responds as if it did not exist);
 *   · a failed call is recorded in `agent_audit_logs` (`tool_call`) with the
 *     code and the invented keys, and WITHOUT the argument values.
 */
describe("MCP: per-operation guide and call audit", () => {
  const URI = "kitsuden://guide/blog__create-post";

  beforeAll(async () => {
    dbAvailable = await isDatabaseAvailable();
  });
  afterAll(async () => {
    for (const s of open) await s.close();
  });

  itWithBlog("resources/list and resources/read: the guide for whoever sees the tool", async () => {
    if (!dbAvailable) return;
    const writer = await mcpSession(["mcp:connect", "blog:*"]);
    expect(await toolsValue(writer)).toContain("blog__create-post");

    const list = await rpc(writer, "resources/list", {});
    const uris = (list.result.resources as { uri: string }[]).map((r) => r.uri);
    expect(uris).toContain(URI);

    const read = await rpc(writer, "resources/read", { uri: URI });
    const [content] = read.result.contents as { uri: string; mimeType: string; text: string }[];
    expect(content!.mimeType).toBe("text/markdown");
    expect(content!.text).toContain("## When to use");
    expect(content!.text).toContain("blog__update-post");
    expect(content!.text).toContain("tagIds");
    expect(content!.text).toContain("## Examples");

    // The tool's description points to the resource
    const tools = (await rpc(writer, "tools/list", {})).result.tools as {
      name: string;
      description: string;
    }[];
    expect(tools.find((t) => t.name === "blog__create-post")!.description).toContain(URI);
  });

  it("without access to the tool, the guide does not exist for the session", async () => {
    if (!dbAvailable) return;
    const foreign = await mcpSession(["mcp:connect"]);
    expect(await toolsValue(foreign)).not.toContain("blog__create-post");

    const list = await rpc(foreign, "resources/list", {});
    expect((list.result.resources as { uri: string }[]).map((r) => r.uri)).not.toContain(URI);

    const read = await rpc(foreign, "resources/read", { uri: URI });
    expect(read.error.code).toBe(-32002);
  });

  itWithBlog(
    "tools/call is recorded in agent_audit_logs with the code and the keys, without values",
    async () => {
      if (!dbAvailable) return;
      const writer = await mcpSession(["mcp:connect", "blog:*"]);
      const secret = `do-not-store-${generateTestId()}`;

      const r = await rpc(writer, "tools/call", {
        name: "blog__create-post",
        arguments: { tags: [secret], body: { title: secret } },
      });
      expect(r.result.isError).toBe(true);
      expect(r.result.structuredContent.code).toBe("KITSUDEN_E_VALIDATION");

      // The audit is asynchronous (it does not delay the response): we wait a bit
      const filter = and(
        eq(agentAuditLogs.agentId, writer.agentId),
        eq(agentAuditLogs.action, "tool_call"),
        eq(agentAuditLogs.resource, "blog__create-post")
      );
      let rows: (typeof agentAuditLogs.$inferSelect)[] = [];
      for (let i = 0; i < 40 && rows.length === 0; i++) {
        rows = await db.select().from(agentAuditLogs).where(filter);
        if (rows.length === 0) await new Promise((ok) => setTimeout(ok, 50));
      }
      expect(rows.length).toBe(1);
      const row = rows[0]!;
      expect(row.success).toBe(false);
      expect(row.errorMessage).toBe("KITSUDEN_E_VALIDATION");
      expect(row.details).toMatchObject({
        origin: "mcp",
        success: false,
        code: "KITSUDEN_E_VALIDATION",
        unknownKeys: ["tags"],
        args: ["body", "tags"],
      });
      expect(JSON.stringify(row)).not.toContain(secret);
    }
  );
});
