/**
 * TypeScript type generator
 * ============================================================================
 *
 * A badly generated type does not fail: it silently spreads through all the code of
 * whoever uses it, and shows up months later as a runtime bug. That is why the
 * generator is pure and this tests it case by case.
 *
 * The three that matter most:
 *   - `bigint` is NOT `number` in JS without losing precision.
 *   - `jsonb` is NOT `any`, because `any` turns off checking entirely.
 *   - Whatever has a default is OPTIONAL on insert, or the user ends up
 *     making up the `id` or casting.
 */

import { describe, expect, test } from "vitest";

import {
  generateTypes,
  isOptionalOnInsert,
  mapColumnType,
  propertyKey,
  toPascalCase,
  type IntrospectedColumn,
  type IntrospectedTable,
} from "../../packages/codegen/src/generators/types";

function col(name: string, type: string, over: Partial<IntrospectedColumn> = {}) {
  return {
    name,
    type,
    nullable: false,
    defaultValue: null,
    isPrimaryKey: false,
    ...over,
  } as IntrospectedColumn;
}

const POSTS: IntrospectedTable = {
  name: "blog_posts",
  columns: [
    col("id", "uuid", { isPrimaryKey: true, defaultValue: "gen_random_uuid()" }),
    col("title", "text"),
    col("excerpt", "text", { nullable: true }),
    col("views", "int4", { defaultValue: "0" }),
    col("content", "jsonb", { nullable: true }),
    col("author_id", "uuid", {
      nullable: true,
      isForeignKey: true,
      foreignTable: "auth_users",
      foreignColumn: "id",
    }),
    col("created_at", "timestamptz", { defaultValue: "now()" }),
  ],
  primaryKey: ["id"],
};

// ── Type mapping ─────────────────────────────────────────────────────────────

describe("Postgres → TypeScript mapping", () => {
  test("common types", () => {
    expect(mapColumnType("text")).toBe("string");
    expect(mapColumnType("uuid")).toBe("string");
    expect(mapColumnType("int4")).toBe("number");
    expect(mapColumnType("boolean")).toBe("boolean");
  });

  test("big integers are STRING, not number", () => {
    // The Postgres driver returns them as strings because they do not fit in a
    // JS number. Typing them as number is a silent bug as soon as the
    // ids grow.
    expect(mapColumnType("bigint")).toBe("string");
    expect(mapColumnType("int8")).toBe("string");
    expect(mapColumnType("numeric")).toBe("string");
    expect(mapColumnType("decimal")).toBe("string");
  });

  test("dates are strings: they travel as ISO over JSON", () => {
    expect(mapColumnType("timestamptz")).toBe("string");
    expect(mapColumnType("date")).toBe("string");
  });

  test("jsonb is UNKNOWN, never any", () => {
    // `any` would turn off checking for everything that touches that field, which is the
    // opposite of generating types. `unknown` forces narrowing.
    expect(mapColumnType("jsonb")).toBe("unknown");
    expect(mapColumnType("json")).toBe("unknown");
  });

  test("arrays in both Postgres notations", () => {
    expect(mapColumnType("_text")).toBe("string[]");
    expect(mapColumnType("text[]")).toBe("string[]");
    expect(mapColumnType("_int4")).toBe("number[]");
  });

  test("an unknown type falls back to unknown, not any", () => {
    expect(mapColumnType("weird_extension_type")).toBe("unknown");
  });
});

// ── Identifiers ──────────────────────────────────────────────────────────────

describe("identifiers", () => {
  test("table name to PascalCase", () => {
    expect(toPascalCase("blog_posts")).toBe("BlogPosts");
    expect(toPascalCase("member-access")).toBe("MemberAccess");
  });

  test("quotes keys that are not valid identifiers", () => {
    // Without this, a column named `2fa_enabled` generates a file that does not
    // compile and the user does not know why.
    expect(propertyKey("title")).toBe("title");
    expect(propertyKey("2fa_enabled")).toBe('"2fa_enabled"');
    expect(propertyKey("user-id")).toBe('"user-id"');
    expect(propertyKey("order")).toBe("order"); // reserved word but valid key
  });
});

// ── Optionality on insert ────────────────────────────────────────────────────

describe("what is optional on insert", () => {
  test("what has a default", () => {
    expect(isOptionalOnInsert(col("views", "int4", { defaultValue: "0" }))).toBe(true);
  });

  test("nullable", () => {
    expect(isOptionalOnInsert(col("excerpt", "text", { nullable: true }))).toBe(true);
  });

  test("an autogenerated PK, even if it declares no default", () => {
    // Requiring an id that Postgres generates forces making it up or casting.
    expect(isOptionalOnInsert(col("id", "uuid", { isPrimaryKey: true }))).toBe(true);
  });

  test("a truly required column is NOT optional", () => {
    expect(isOptionalOnInsert(col("title", "text"))).toBe(false);
  });
});

// ── Broadcast ────────────────────────────────────────────────────────────────

describe("generated file", () => {
  const out = generateTypes([POSTS]);

  test("emits Row, Insert and Update per table", () => {
    expect(out).toContain("export interface BlogPostsRow");
    expect(out).toContain("export interface BlogPostsInsert");
    expect(out).toContain("export type BlogPostsUpdate");
  });

  test("in Row everything is present; nullable ones carry | null", () => {
    const row = out.slice(
      out.indexOf("interface BlogPostsRow"),
      out.indexOf("interface BlogPostsInsert")
    );
    expect(row).toMatch(/title: string;/);
    expect(row).toMatch(/excerpt: string \| null;/);
    // The id is NOT optional on read: it always comes.
    expect(row).toMatch(/id: string;/);
  });

  test("in Insert what is autogenerated is optional", () => {
    const insert = out.slice(
      out.indexOf("interface BlogPostsInsert"),
      out.indexOf("BlogPostsUpdate")
    );
    expect(insert).toMatch(/id\?: string;/);
    expect(insert).toMatch(/views\?: number;/);
    expect(insert).toMatch(/created_at\?: string;/);
    // But the title is still required.
    expect(insert).toMatch(/\n {2}title: string;/);
  });

  test("Update excludes the primary key", () => {
    // Changing the PK is not updating, it is another row.
    expect(out).toMatch(/BlogPostsUpdate = Partial<Omit<BlogPostsInsert, "id">>/);
  });

  test("documents foreign keys in the type itself", () => {
    expect(out).toMatch(/→ auth_users\.id/);
  });

  test("emits the Database map and its helpers", () => {
    expect(out).toContain("export interface Database");
    expect(out).toMatch(/blog_posts: \{/);
    expect(out).toContain("export type Row<T extends TableName>");
    expect(out).toContain("export type TableName = keyof Database");
  });

  test("warns that it is generated", () => {
    expect(out).toMatch(/DO NOT EDIT BY HAND/);
  });
});

// ── Determinism ──────────────────────────────────────────────────────────────

describe("determinism", () => {
  test("the same schema produces the same file", () => {
    // Without this, regenerating would dirty every commit with a noisy diff.
    expect(generateTypes([POSTS])).toBe(generateTypes([POSTS]));
  });

  test("input order does not change the output", () => {
    const other: IntrospectedTable = { name: "tags", columns: [col("id", "uuid")] };
    expect(generateTypes([POSTS, other])).toBe(generateTypes([other, POSTS]));
  });

  test("neither does column order", () => {
    const reversed: IntrospectedTable = { ...POSTS, columns: [...POSTS.columns].reverse() };
    expect(generateTypes([reversed])).toBe(generateTypes([POSTS]));
  });
});

// ── Edge cases ───────────────────────────────────────────────────────────────

describe("edge cases", () => {
  test("with no tables it emits an empty Database that compiles", () => {
    const out = generateTypes([]);
    expect(out).toContain("export interface Database {}");
  });

  test("respects exclusions", () => {
    const out = generateTypes([POSTS], { exclude: ["blog_posts"] });
    expect(out).not.toContain("BlogPostsRow");
  });

  test("ignores tables without columns instead of emitting garbage", () => {
    const out = generateTypes([{ name: "empty", columns: [] }]);
    expect(out).not.toContain("EmptyRow");
  });

  test("a table without a PK generates Update without a broken Omit", () => {
    const out = generateTypes([{ name: "log", columns: [col("msg", "text")] }]);
    expect(out).toMatch(/LogUpdate = Partial<Omit<LogInsert, never>>/);
  });
});
