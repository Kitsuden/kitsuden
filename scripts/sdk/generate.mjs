const literalPy = (v) =>
  v === null
    ? "None"
    : v === true
      ? "True"
      : v === false
        ? "False"
        : typeof v === "string"
          ? JSON.stringify(v)
          : String(v);

function unionPy(parts) {
  const unique = [...new Set(parts)];
  if (unique.includes("Any")) return "Any";
  if (unique.length === 0) return "Any";
  if (unique.length === 1) return unique[0];
  const withoutNone = unique.filter((u) => u !== "None");
  if (withoutNone.length < unique.length) {
    return withoutNone.length === 1
      ? `Optional[${withoutNone[0]}]`
      : `Optional[Union[${withoutNone.join(", ")}]]`;
  }
  return `Union[${unique.join(", ")}]`;
}

/** The TypedDicts of one Python module, deduplicated by shape. */
class PyTypes {
  constructor() {
    this.bySignature = new Map();
    this.names = new Set();
    this.defs = [];
  }

  freeName(base) {
    let n = base;
    for (let i = 2; this.names.has(n); i++) n = `${base}${i}`;
    this.names.add(n);
    return n;
  }

  type(s, name, width = false) {
    if (s === true || s === undefined || s === null) return "Any";
    if (s === false) return "Any";
    if (typeof s !== "object") return "Any";
    if (s.$ref) return s.$ref === "#/components/schemas/Problem" ? "Problem" : "Any";
    if ("const" in s) return `Literal[${literalPy(s.const)}]`;
    if (Array.isArray(s.enum)) {
      const values = s.enum.filter((v) => v !== null && typeof v !== "object");
      const withNone = s.enum.includes(null);
      if (values.length === 0) return withNone ? "None" : "Any";
      const lit = `Literal[${values.map(literalPy).join(", ")}]`;
      return withNone ? `Optional[${lit}]` : lit;
    }
    if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) {
      const ms = (s.anyOf ?? s.oneOf).map((m, i) =>
        this.type(m, `${name}${i === 0 ? "" : `V${i + 1}`}`, width)
      );
      return unionPy(ms);
    }
    if (Array.isArray(s.allOf)) {
      const objects = s.allOf.filter(
        (m) => m && typeof m === "object" && (m.type === "object" || m.properties)
      );
      if (objects.length === s.allOf.length && objects.length > 0) {
        const props = {};
        const req = [];
        for (const m of objects) {
          Object.assign(props, m.properties ?? {});
          req.push(...(m.required ?? []));
        }
        return this.type({ type: "object", properties: props, required: req }, name, width);
      }
      return "Any";
    }
    if (Array.isArray(s.type))
      return unionPy(s.type.map((t) => this.type({ ...s, type: t }, name, width)));
    switch (s.type) {
      case "string":
        return width ? "Union[str, int]" : "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "null":
        return "None";
      case "array":
        if (Array.isArray(s.prefixItems)) {
          return `List[${unionPy(s.prefixItems.map((m, i) => this.type(m, `${name}Item${i + 1}`)))}]`;
        }
        return `List[${this.type(s.items ?? {}, `${name}Item`)}]`;
      case "object":
        return this.object(s, name);
      default:
        if (s.properties || s.additionalProperties) return this.object(s, name);
        return "Any";
    }
  }

  object(s, name) {
    const props = s.properties ?? {};
    const keys = Object.keys(props);
    if (keys.length === 0) {
      const extra = s.additionalProperties;
      return `Dict[str, ${extra && extra !== true ? this.type(extra, `${name}Value`) : "Any"}]`;
    }
    const requiredValues = new Set(s.required ?? []);
    const fields = keys.map((k) => ({
      key: k,
      required: requiredValues.has(k),
      type: this.type(props[k], `${name}${pascal(k) || "Field"}`),
      description: props[k]?.description ?? "",
    }));
    const signature = JSON.stringify(fields.map((c) => [c.key, c.required, c.type]));
    const prior = this.bySignature.get(signature);
    if (prior) return prior;
    const n = this.freeName(name);
    this.bySignature.set(signature, n);
    this.defs.push({ name: n, fields, description: s.description ?? "" });
    return n;
  }

  emit() {
    let out = "";
    for (const d of this.defs) out += typedDictPy(d);
    return out;
  }
}

function docPy(text, indent) {
  const t = String(text ?? "").trim();
  if (!t) return "";
  const clean = t.replaceAll("\\", "\\\\").replaceAll('"""', '\\"\\"\\"');
  const lines = clean.split(/\r?\n/);
  if (lines.length === 1) return `${indent}"""${lines[0]}"""\n`;
  return `${indent}"""${lines[0]}\n${lines
    .slice(1)
    .map((l) => (l ? `${indent}${l}` : ""))
    .join("\n")}\n${indent}"""\n`;
}

function typedDictPy({ name: name, fields: fields, description: description }) {
  const req = fields.filter((c) => c.required);
  const opc = fields.filter((c) => !c.required);
  const allIdent = fields.every((c) => isPyIdent(c.key));
  let out = "";
  if (allIdent) {
    if (req.length && opc.length) {
      out += `class _${name}Required(TypedDict):\n`;
      for (const c of req) out += `    ${c.key}: ${c.type}\n`;
      out += `\n\nclass ${name}(_${name}Required, total=False):\n`;
      out += docPy(description, "    ");
      for (const c of opc) out += `    ${c.key}: ${c.type}\n`;
    } else {
      out += `class ${name}(TypedDict${req.length ? "" : ", total=False"}):\n`;
      out += docPy(description, "    ");
      for (const c of fields) out += `    ${c.key}: ${c.type}\n`;
    }
  } else {
    const total = opc.length === 0;
    out += `${name} = TypedDict(\n    ${JSON.stringify(name)},\n    {\n`;
    for (const c of fields) out += `        ${JSON.stringify(c.key)}: ${c.type},\n`;
    out += `    },\n    total=${total ? "True" : "False"},\n)\n`;
  }
  return `${out}\n\n`;
}

