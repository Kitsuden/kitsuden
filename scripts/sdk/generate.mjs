function existingOnes(dir) {
  const output = [];
  if (!existsSync(dir)) return output;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "__pycache__") continue;
      output.push(...existingOnes(p));
    } else output.push(p);
  }
  return output;
}

