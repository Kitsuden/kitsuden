const OPTION_PY = "request_options";

function argsPy(op, types) {
  const args = [];
  const used = new Set(["self", OPTION_PY, "body"]);
  for (const p of [...op.ofPath, ...op.fromQuery]) {
    let n = pyIdent(p.name);
    while (used.has(n)) n = `${n}_`;
    used.add(n);
    const type = types.type(
      p.schema ?? { type: "string" },
      `${op.type}Param${pascal(p.name)}`,
      true
    );
    const required = p.in === "path" || p.required;
    args.push({
      py: n,
      wire: p.name,
      type,
      required,
      description: p.description ?? p.schema?.description ?? "",
    });
  }
  return args;
}

function signaturePy(op, args, bodyType) {
  const parts = ["self", "*"];
  const list = args;
  for (const a of list.filter((x) => x.required)) parts.push(`${a.py}: ${a.type}`);
  if (op.body?.required) parts.push(`body: ${bodyType}`);
  for (const a of list.filter((x) => !x.required))
    parts.push(`${a.py}: Optional[${a.type}] = None`);
  if (op.body && !op.body.required) parts.push(`body: Optional[${bodyType}] = None`);
  parts.push(`${OPTION_PY}: Optional[RequestOptions] = None`);
  return parts.join(", ");
}

function mapPy(args) {
  if (!args.length) return "{}";
  return `{${args.map((a) => `${JSON.stringify(a.wire)}: ${a.py}`).join(", ")}}`;
}

function docOpPy(op, args) {
  let t = operationDoc(op);
  const withDesc = args.filter((a) => a.description);
  if (withDesc.length)
    t += `\n\nArgs:\n${withDesc.map((a) => `    ${a.py}: ${a.description.replace(/\s+/g, " ")}`).join("\n")}`;
  return t;
}

function infoPy(op) {
  const i = operationInfo(op);
  // The Python client reads a stream as text (the raw SSE).
  const resp = Object.entries(i.responses)
    .map(([k, v]) => `${k}: ${JSON.stringify(v === "event-stream" ? "text" : v)}`)
    .join(", ");
  const tuple = (xs) =>
    xs.length
      ? `(${xs.map((x) => JSON.stringify(x)).join(", ")}${xs.length === 1 ? "," : ""})`
      : "()";
  let out = `OperationInfo(\n`;
  out += `        kon=${JSON.stringify(i.kon)},\n        id=${JSON.stringify(i.id)},\n        operation_id=${JSON.stringify(i.operationId)},\n`;
  out += `        method=${JSON.stringify(i.method)},\n        path=${JSON.stringify(i.path)},\n`;
  out += `        path_params=${tuple(i.pathParams)},\n        query_params=${tuple(i.queryParams)},\n`;
  out += `        body=${i.body ? JSON.stringify(i.body) : "None"},\n        responses={${resp}},\n`;
  out += `        idempotent=${i.idempotent ? "True" : "False"},\n        read_only=${i.readOnly ? "True" : "False"},\n`;
  out += `        sensitive=${i.sensitive ? "True" : "False"},\n        scope=${i.scope ? JSON.stringify(i.scope) : "None"},\n`;
  out += `        mcp_tool=${i.mcpTool ? JSON.stringify(i.mcpTool) : "None"},\n        errors=${tuple(i.errors)},\n`;
  if (i.pagination) {
    out += `        pagination=PaginationInfo(style=${JSON.stringify(i.pagination.style)}, items=${i.pagination.items === null ? "None" : JSON.stringify(i.pagination.items)}, limit=${i.pagination.limit ? JSON.stringify(i.pagination.limit) : "None"}),\n`;
  }
  out += `    )`;
  return out;
}

function pyResponse(op, types) {
  const parts = op.successes.map((e, i) => {
    if (e.kind === "json")
      return types.type(e.schema ?? {}, `${op.type}Response${i === 0 ? "" : e.status}`);
    if (e.kind === "text" || e.kind === "event-stream") return "str";
    if (e.kind === "binary") return "bytes";
    if (e.kind === "redirect") return "RedirectResult";
    return "None";
  });
  return unionPy(parts);
}

function generatePyKon(k) {
  const types = new PyTypes();
  const methods = [];
  for (const op of k.ops) {
    const args = argsPy(op, types);
    let bodyType = null;
    if (op.body) {
      bodyType =
        op.body.format === "multipart"
          ? "Dict[str, Any]"
          : types.type(op.body.schema, `${op.type}Body`);
    }
    const response = pyResponse(op, types);
    const item = op.pagination ? types.type(op.pagination.itemSchema, `${op.type}Item`) : null;
    methods.push({ op, args, bodyType, response, item });
  }
  const alias = [];
  for (const m of methods) {
    // `X = None` is not a valid type alias for checkers; `Literal[None]` is the same type.
    alias.push(`${m.op.type}Result = ${m.response === "None" ? "Literal[None]" : m.response}`);
  }

  let out = `# ${HEADER}\n# ${k.id}\n# fmt: off\n# flake8: noqa\n`;
  out += `from __future__ import annotations\n\n`;
  out += `from typing import Any, AsyncIterator, Dict, Iterator, List, Literal, Optional, Union\n\n`;
  out += `from typing import TypedDict\n\n`;
  out += `from ..._runtime import (\n    AsyncKonApi,\n    KonApi,\n    OperationInfo,\n    Outcome,\n    PaginationInfo,\n    Problem,\n    RedirectResult,\n    RequestOptions,\n)\n\n`;
  out += `__all__ = ["${k.type}Api", "Async${k.type}Api", "OPERATIONS"]\n\n\n`;
  out += types.emit();
  out += alias.join("\n") + "\n\n\n";
  out += `OPERATIONS: Dict[str, OperationInfo] = {\n`;
  for (const { op } of methods) out += `    ${JSON.stringify(op.id)}: ${infoPy(op)},\n`;
  out += `}\n\n\n`;

  for (const async of [false, true]) {
    const kind = async ? `Async${k.type}Api` : `${k.type}Api`;
    out += `class ${kind}(${async ? "AsyncKonApi" : "KonApi"}):\n`;
    out += docPy(`${k.id}${k.description ? `\n\n${k.description}` : ""}`, "    ");
    out += `\n    kon = ${JSON.stringify(k.id)}\n`;
    for (const m of methods) {
      const { op, args, bodyType } = m;
      out += `\n    ${async ? "async " : ""}def ${op.py}(${signaturePy(op, args, bodyType)}) -> Outcome[${op.type}Result]:\n`;
      out += docPy(docOpPy(op, args), "        ");
      out += `        return ${async ? "await " : ""}self._call(OPERATIONS[${JSON.stringify(op.id)}], ${mapPy(args)}, ${op.body ? "body" : "None"}, ${OPTION_PY})\n`;
      if (op.pagination) {
        const move =
          op.pagination.style === "cursor"
            ? "cursor"
            : op.pagination.style === "page"
              ? "page"
              : "offset";
        const without = args.filter((a) => a.wire !== move);
        const signature = signaturePy({ ...op, body: null }, without, null);
        const it = async ? "AsyncIterator" : "Iterator";
        out += `\n    def iter_${op.py}(${signature}) -> ${it}[${m.item}]:\n`;
        out += docPy(
          `Every item of \`${op.py}\`, page after page (moves \`${move}\`).\n\nStops on an empty or short page, or when the response says there is no more. Raises \`ProposalPendingError\` if a page needs human approval.`,
          "        "
        );
        out += `        return self._iterate(OPERATIONS[${JSON.stringify(op.id)}], ${mapPy(without)}, ${OPTION_PY})\n`;
      }
    }
    out += `\n\n`;
  }
  return out.replace(/\n{3,}$/, "\n");
}

