#!/usr/bin/env node
/**
 * Typed clients (TypeScript + Python) from the OpenAPI 3.1 of the kon SDK
 * ============================================================================
 *
 * Input: `packages/sdk/openapi/kitsuden.openapi.json`, the document that
 * `apps/api/scripts/sdk-openapi.ts` writes from every `defineOperation` of the
 * installed kons and the core (same function as `GET /api/docs/openapi.json`).
 *
 * Output (never edit by hand; regenerate):
 *
 *   packages/sdk/src/generated/            TypeScript: one file per kon + index
 *   packages/sdk-python/kitsuden/_generated/  Python: one module per kon + index
 *
 * Deterministic on purpose: no dates, no absolute paths, everything sorted, so
 * running it twice gives the same bytes and CI can diff the result.
 *
 *   node scripts/sdk/generate.mjs                 # write
 *   node scripts/sdk/generate.mjs --check         # exit 1 if the committed code is stale
 *   node scripts/sdk/generate.mjs --spec=<file>   # another OpenAPI document
 *   node scripts/sdk/generate.mjs --from-url=<API origin>
 *        # fetch <API>/api/docs/openapi.json, keep the kon SDK operations
 *        # (`x-kitsuden-operation`), write it as the snapshot, then generate:
 *        # for a project whose installed kons are not in this repository.
 *   node scripts/sdk/generate.mjs --from-kon=<kon folder> [--from-kon=<another>]
 *        # no running API and no database: build the OpenAPI of that kon's
 *        # `defineOperation` declarations (apps/api/scripts/sdk-openapi.ts --kon,
 *        # run with Bun), merge it into the snapshot (the other kons stay), then
 *        # generate. Same document shape as --from-url, so the same clients.
 *
 * No dependencies: plain Node (>= 18). No third-party generator, so no license
 * to check; the JSON Schema → TypeScript / Python mapping is below.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const DEFAULT_SPEC = join(ROOT, "packages/sdk/openapi/kitsuden.openapi.json");
const args = process.argv.slice(2);
const arg = (n) => args.find((a) => a.startsWith(`--${n}=`))?.slice(n.length + 3);

// `--out-ts` / `--out-py`: another folder (the generator's tests).
const DIR_TS = resolve(arg("out-ts") ?? join(ROOT, "packages/sdk/src/generated"));
const DIR_PY = resolve(arg("out-py") ?? join(ROOT, "packages/sdk-python/kitsuden/_generated"));
const check = args.includes("--check");
const specPath = resolve(arg("spec") ?? DEFAULT_SPEC);
const fromUrl = arg("from-url");
const fromKon = args.filter((a) => a.startsWith("--from-kon=")).map((a) => resolve(a.slice(11)));

const HEADER =
  "Generated by scripts/sdk/generate.mjs from packages/sdk/openapi/kitsuden.openapi.json. Do not edit: run `pnpm sdk:generate`.";

// ═════════════════════════════════════════════════════════════════════════════
// 1. The document
// ═════════════════════════════════════════════════════════════════════════════

/**
 * `--from-kon`: the kon's operations come from its declarations, not from a server.
 * The OpenAPI is built by the same function the API uses (`openApiOperation`), in
 * Bun because the kon is TypeScript and imports `@kitsuden/engine`.
 */
function snapshotFromKons(dirs) {
  if (fromUrl) throw new Error("--from-kon and --from-url do not go together");
  if (check) throw new Error("--from-kon writes the snapshot; run --check afterwards");
  const bun = process.env.BUN_BINARY || "bun";
  const quote = (a) => (process.platform === "win32" && /\s/.test(a) ? `"${a}"` : a);
  const r = spawnSync(
    quote(bun),
    [
      "--no-env-file",
      join(ROOT, "apps/api/scripts/sdk-openapi.ts"),
      `--out=${specPath}`,
      ...dirs.map((d) => `--kon=${d}`),
    ].map(quote),
    {
      cwd: join(ROOT, "apps/api"),
      encoding: "utf8",
      stdio: ["ignore", "inherit", "inherit"],
      // `bun` is `bun.exe` or a shim on Windows: the shell finds either.
      shell: process.platform === "win32",
    }
  );
  if (r.error) throw new Error(`could not run Bun (${bun}): ${r.error.message}`);
  if (r.status !== 0) throw new Error(`sdk-openapi --kon failed (exit ${r.status})`);
}

async function loadSpec() {
  if (fromKon.length) snapshotFromKons(fromKon);
  if (fromUrl) {
    const base = fromUrl.replace(/\/+$/, "").replace(/\/api$/, "");
    const res = await fetch(`${base}/api/docs/openapi.json`, {
      headers: { accept: "application/json" },
    });
    if (!res.ok) throw new Error(`GET ${base}/api/docs/openapi.json → ${res.status}`);
    const alive = await res.json();
    const paths = {};
    for (const path of Object.keys(alive.paths ?? {}).sort()) {
      for (const method of ["get", "put", "post", "delete", "patch"]) {
        const o = alive.paths[path]?.[method];
        if (!o?.["x-kitsuden-operation"]) continue;
        (paths[path] ??= {})[method] = o;
      }
    }
    const kons = new Set(
      Object.values(paths).flatMap((i) =>
        Object.values(i).map((o) => o["x-kitsuden-operation"].kon)
      )
    );
    const doc = {
      openapi: "3.1.0",
      info: { ...alive.info, title: "Kitsuden API — kon SDK operations" },
      servers: alive.servers,
      tags: (alive.tags ?? [])
        .filter((t) => kons.has(t.name))
        .sort((a, b) => a.name.localeCompare(b.name)),
      paths,
      components: {
        schemas: { Problem: alive.components.schemas.Problem },
        securitySchemes: alive.components.securitySchemes,
      },
    };
    mkdirSync(dirname(specPath), { recursive: true });
    writeFileSync(specPath, `${JSON.stringify(doc, null, 2)}\n`);
    console.error(`[sdk] snapshot from ${base}: ${rel(specPath)}`);
    return doc;
  }
  if (!existsSync(specPath))
    throw new Error(`${rel(specPath)} does not exist: run pnpm sdk:openapi first`);
  return JSON.parse(readFileSync(specPath, "utf8"));
}

function rel(p) {
  return relative(ROOT, p).replaceAll("\\", "/");
}

// ═════════════════════════════════════════════════════════════════════════════
// 2. Names
// ═════════════════════════════════════════════════════════════════════════════

const words = (s) =>
  String(s)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w.toLowerCase());
const camel = (s) => {
  const w = words(s);
  const r = w.map((x, i) => (i === 0 ? x : x[0].toUpperCase() + x.slice(1))).join("");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};
const pascal = (s) => {
  const r = words(s)
    .map((x) => x[0].toUpperCase() + x.slice(1))
    .join("");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};
const snake = (s) => {
  const r = words(s).join("_");
  return /^[0-9]/.test(r) ? `_${r}` : r;
};

const PY_KEYWORDS = new Set(
  "False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield".split(
    " "
  )
);
const pyIdent = (s) => {
  const n = snake(s) || "_";
  return PY_KEYWORDS.has(n) ? `${n}_` : n;
};
const isTsIdent = (k) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k);
const isPyIdent = (k) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !PY_KEYWORDS.has(k);

/** Names the clients use for their own members: a kon cannot take them. */
const RESERVED_TS = new Set([
  "request",
  "withOptions",
  "operations",
  "options",
  "baseUrl",
  "constructor",
  "toString",
]);
const RESERVED_PY = new Set(["request", "operations", "options", "base_url", "close", "aclose"]);

// ═════════════════════════════════════════════════════════════════════════════
// 3. The model: kons → operations
// ═════════════════════════════════════════════════════════════════════════════

const METHOD_ORDER = ["get", "put", "post", "delete", "patch"];
const ITEM_FIELDS = ["docs", "data", "items", "rows", "results", "entries"];

function contentType(type) {
  if (!type) return "empty";
  // A stream: Server-Sent Events, one JSON event per `data:`.
  if (type === "text/event-stream") return "event-stream";
  if (type === "application/json" || type.endsWith("+json")) return "json";
  if (type.startsWith("text/") || type === "application/javascript") return "text";
  return "binary";
}

function buildModel(doc) {
  const konDescription = new Map((doc.tags ?? []).map((t) => [t.name, t.description ?? ""]));
  const kons = new Map();
  for (const path of Object.keys(doc.paths).sort()) {
    for (const method of METHOD_ORDER) {
      const o = doc.paths[path][method];
      if (!o) continue;
      const x = o["x-kitsuden-operation"];
      if (!x) continue;
      const konId = x.kon;
      if (!kons.has(konId)) {
        const shortOne = konId.replace(/^kon-/, "");
        kons.set(konId, {
          id: konId,
          short: shortOne,
          ts: camel(shortOne),
          py: pyIdent(shortOne),
          type: pascal(shortOne),
          description: konDescription.get(konId) ?? "",
          ops: [],
        });
      }
      const params = o.parameters ?? [];
      const ofPath = params.filter((p) => p.in === "path");
      const fromQuery = params.filter((p) => p.in === "query");
      const names = new Set();
      for (const p of [...ofPath, ...fromQuery]) {
        if (names.has(p.name))
          throw new Error(
            `${o.operationId}: parameter '${p.name}' is both in the path and the query`
          );
        if (p.name === "body")
          throw new Error(`${o.operationId}: a parameter cannot be called 'body'`);
        names.add(p.name);
      }
      let body = null;
      if (o.requestBody) {
        const [type, media] = Object.entries(o.requestBody.content)[0];
        body = {
          required: !!o.requestBody.required,
          format: type === "multipart/form-data" ? "multipart" : "json",
          schema: media.schema ?? {},
        };
      }
      const successes = [];
      for (const status of Object.keys(o.responses).sort()) {
        const n = Number(status);
        if (!(n >= 200 && n < 400)) continue;
        const r = o.responses[status];
        const [type, media] = Object.entries(r.content ?? {})[0] ?? [];
        const kind = n >= 300 ? "redirect" : n === 204 ? "empty" : contentType(type);
        // In a stream, the schema that matters is the one of EACH event.
        const schema =
          kind === "event-stream"
            ? (media?.["x-kitsuden-event-schema"] ?? null)
            : (media?.schema ?? null);
        successes.push({ status: n, type: type ?? null, kind, schema });
      }
      const op = {
        kon: konId,
        id: x.id,
        operationId: o.operationId,
        ts: camel(x.id),
        py: pyIdent(x.id),
        type: pascal(x.id),
        method: method.toUpperCase(),
        path,
        summary: o.summary ?? "",
        description: o.description ?? "",
        ofPath,
        fromQuery: fromQuery,
        body,
        successes: successes,
        errors: [...(x.errors ?? [])],
        idempotent: !!x.idempotent,
        readOnly: !!x.readOnly,
        sensitive: !!x.sensitive,
        scope: x.scope ?? null,
        access: x.access ?? null,
        mcp: x.mcp?.tool ?? null,
        flow: x.stream === true,
        pagination: null,
      };
      // A stream is not paginated: it is already an iterable.
      op.pagination = op.flow ? null : paginationOf(op);
      kons.get(konId).ops.push(op);
    }
  }
  const list = [...kons.values()].sort((a, b) => a.id.localeCompare(b.id));
  const seenTs = new Set();
  const seenPy = new Set();
  for (const k of list) {
    if (RESERVED_TS.has(k.ts) || seenTs.has(k.ts))
      throw new Error(`kon ${k.id}: TS name '${k.ts}' is taken`);
    if (RESERVED_PY.has(k.py) || seenPy.has(k.py))
      throw new Error(`kon ${k.id}: Python name '${k.py}' is taken`);
    seenTs.add(k.ts);
    seenPy.add(k.py);
    k.ops.sort((a, b) => a.id.localeCompare(b.id));
    const ts = new Set();
    const py = new Set();
    for (const op of k.ops) {
      if (ts.has(op.ts)) throw new Error(`${k.id}: two operations named '${op.ts}'`);
      if (py.has(op.py)) throw new Error(`${k.id}: two operations named '${op.py}'`);
      ts.add(op.ts);
      py.add(op.py);
    }
  }
  return list;
}

/** Page/offset/cursor lists: which query parameter moves and where the items are. */
function paginationOf(op) {
  const q = op.fromQuery.map((p) => p.name);
  const style = q.includes("cursor")
    ? "cursor"
    : q.includes("page")
      ? "page"
      : q.includes("offset")
        ? "offset"
        : null;
  if (!style || op.method !== "GET") return null;
  const success = op.successes.find((e) => e.kind === "json");
  const schema = success?.schema;
  let items = null;
  let itemSchema = {};
  if (schema?.type === "array") {
    items = "";
    itemSchema = schema.items ?? {};
  } else if (schema?.properties) {
    const arrays = Object.entries(schema.properties).filter(([, s]) => s?.type === "array");
    const chosenItem =
      arrays.find(([k]) => ITEM_FIELDS.includes(k)) ??
      (arrays.length === 1 ? arrays[0] : undefined);
    if (chosenItem) {
      items = chosenItem[0];
      itemSchema = chosenItem[1].items ?? {};
    }
  }
  return {
    style,
    items,
    itemSchema,
    limit: q.includes("limit") ? "limit" : q.includes("pageSize") ? "pageSize" : null,
  };
}

// ═════════════════════════════════════════════════════════════════════════════
// 4. JSON Schema → TypeScript
// ═════════════════════════════════════════════════════════════════════════════

const jsdoc = (text, indent) => {
  const t = String(text ?? "").trim();
  if (!t) return "";
  const lines = t.replaceAll("*/", "*\\/").split(/\r?\n/);
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ""}`).join("\n")}\n${indent} */\n`;
};

const literalTs = (v) => (v === null ? "null" : JSON.stringify(v));

function unionTs(parts) {
  const unique = [...new Set(parts)];
  if (unique.includes("unknown")) return "unknown";
  return unique.length === 0 ? "never" : unique.join(" | ");
}

/**
 * `width`: query/path parameters travel as text, so a `string` there also
 * takes a number (the URL is the same).
 */
function ts(s, indent = "", width = false) {
  if (s === true || s === undefined || s === null) return "unknown";
  if (s === false) return "never";
  if (typeof s !== "object") return "unknown";
  if (s.$ref) {
    if (s.$ref === "#/components/schemas/Problem") return "Problem";
    return "unknown";
  }
  if ("const" in s) return literalTs(s.const);
  if (Array.isArray(s.enum)) return unionTs(s.enum.map(literalTs));
  if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) {
    const ms = (s.anyOf ?? s.oneOf).map((m) => wrap(ts(m, indent, width)));
    return unionTs(ms);
  }
  if (Array.isArray(s.allOf)) {
    const ms = s.allOf.map((m) => wrap(ts(m, indent, width))).filter((m) => m !== "unknown");
    return ms.length ? [...new Set(ms)].join(" & ") : "unknown";
  }
  if (Array.isArray(s.type)) {
    return unionTs(s.type.map((t) => wrap(ts({ ...s, type: t }, indent, width))));
  }
  switch (s.type) {
    case "string":
      return width ? "string | number" : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      if (Array.isArray(s.prefixItems)) {
        const items = s.prefixItems.map((m) => ts(m, indent));
        return `[${items.join(", ")}]`;
      }
      return `${wrap(ts(s.items ?? {}, indent))}[]`;
    }
    case "object":
      return tsObject(s, indent);
    default:
      if (s.properties || s.additionalProperties) return tsObject(s, indent);
      return "unknown";
  }
}

function wrap(t) {
  return /[|&]/.test(t) && !/^\{[\s\S]*\}$/.test(t) && !/^\[[\s\S]*\]$/.test(t) ? `(${t})` : t;
}

function tsObject(s, indent) {
  const props = s.properties ?? {};
  const requiredValues = new Set(s.required ?? []);
  const keys = Object.keys(props);
  const extra = s.additionalProperties;
  if (keys.length === 0) {
    if (extra === false) return "Record<string, never>";
    const value = extra && extra !== true ? ts(extra, indent) : "unknown";
    const braces =
      s.propertyNames && Array.isArray(s.propertyNames.enum)
        ? unionTs(s.propertyNames.enum.map(literalTs))
        : null;
    return braces ? `Partial<Record<${braces}, ${value}>>` : `Record<string, ${value}>`;
  }
  const inside = `${indent}  `;
  let out = "{\n";
  for (const k of keys) {
    const p = props[k];
    out += jsdoc(p?.description, inside);
    out += `${inside}${isTsIdent(k) ? k : JSON.stringify(k)}${requiredValues.has(k) ? "" : "?"}: ${ts(p, inside)};\n`;
  }
  if (extra && extra !== false) out += `${inside}[key: string]: unknown;\n`;
  return `${out}${indent}}`;
}

// ═════════════════════════════════════════════════════════════════════════════
// 5. TypeScript output
// ═════════════════════════════════════════════════════════════════════════════

function operationInfo(op) {
  const responses = {};
  for (const e of op.successes) responses[e.status] = e.kind;
  const info = {
    kon: op.kon,
    id: op.id,
    operationId: op.operationId,
    method: op.method,
    path: op.path,
    pathParams: op.ofPath.map((p) => p.name),
    queryParams: op.fromQuery.map((p) => p.name),
    body: op.body ? op.body.format : null,
    responses: responses,
    idempotent: op.idempotent,
    readOnly: op.readOnly,
    sensitive: op.sensitive,
    scope: op.scope,
    mcpTool: op.mcp,
    errors: op.errors,
  };
  if (op.pagination) {
    info.pagination = {
      style: op.pagination.style,
      items: op.pagination.items,
      limit: op.pagination.limit,
    };
  }
  if (op.flow) info.stream = true;
  return info;
}

function operationDoc(op) {
  const lines = [op.summary || op.id];
  if (op.description && op.description !== op.summary) lines.push("", op.description);
  lines.push("", `REST: \`${op.method} /api${op.path}\` · scope \`${op.scope}\``);
  const notes = [];
  notes.push(
    op.idempotent
      ? "idempotent (safe to retry)"
      : "not idempotent (an Idempotency-Key is sent automatically)"
  );
  if (op.sensitive) notes.push("sensitive: may come back as a proposal pending human approval");
  if (op.mcp) notes.push(`MCP tool \`${op.mcp}\``);
  lines.push(notes.join(" · "));
  if (op.errors.length) lines.push(`Errors: ${op.errors.map((c) => `\`${c}\``).join(", ")}`);
  return lines.join("\n");
}

function tsResponse(op) {
  const parts = [];
  for (const e of op.successes) {
    if (e.kind === "json" || e.kind === "event-stream") parts.push(ts(e.schema ?? {}, ""));
    else if (e.kind === "text") parts.push("string");
    else if (e.kind === "binary") parts.push("ArrayBuffer");
    else if (e.kind === "redirect") parts.push("RedirectResult");
    else parts.push("null");
  }
  return unionTs(parts.map(wrap)) || "unknown";
}

function tsParameters(op) {
  if (!op.ofPath.length && !op.fromQuery.length && !op.body) return null;
  let out = "{\n";
  for (const p of op.ofPath) {
    out += jsdoc(p.description ?? p.schema?.description ?? "Path parameter.", "  ");
    out += `  ${isTsIdent(p.name) ? p.name : JSON.stringify(p.name)}: ${ts(p.schema ?? { type: "string" }, "  ", true)};\n`;
  }
  for (const p of op.fromQuery) {
    out += jsdoc(p.description ?? p.schema?.description, "  ");
    out += `  ${isTsIdent(p.name) ? p.name : JSON.stringify(p.name)}${p.required ? "" : "?"}: ${ts(p.schema ?? {}, "  ", true)};\n`;
  }
  if (op.body) {
    const bodyType = op.body.format === "multipart" ? "FormData" : `${op.type}Body`;
    out += jsdoc(op.body.format === "multipart" ? "multipart/form-data body." : "JSON body.", "  ");
    out += `  body${op.body.required ? "" : "?"}: ${bodyType};\n`;
  }
  return `${out}}`;
}

function generateTsKon(k) {
  let out = `// ${HEADER}\n\n`;
  out += `import type { OperationInfo, Operation, PageableOperation, StreamOperation, Problem, RedirectResult } from "../../api/types";\n\n`;
  out += `/* ${k.id}${k.description ? `: ${k.description.replaceAll("*/", "*\\/")}` : ""} */\n\n`;
  const usesProblem = /\bProblem\b/;
  const usesRedirect = /\bRedirectResult\b/;
  let bodyTypes = "";
  for (const op of k.ops) {
    if (op.body && op.body.format === "json") {
      bodyTypes += jsdoc(`Body of \`${op.operationId}\`.`, "");
      bodyTypes += `export type ${op.type}Body = ${ts(op.body.schema, "")};\n\n`;
    }
    const p = tsParameters(op);
    if (p) {
      bodyTypes += jsdoc(
        `Arguments of \`${op.operationId}\`: path and query parameters flat, the body under \`body\` (same shape as its MCP tool).`,
        ""
      );
      bodyTypes += `export type ${op.type}Params = ${p};\n\n`;
    }
    if (op.flow) {
      bodyTypes += jsdoc(`One event of the stream \`${op.operationId}\` (Server-Sent Events).`, "");
      bodyTypes += `export type ${op.type}Event = ${tsResponse(op)};\n\n`;
    } else {
      bodyTypes += jsdoc(`Success response of \`${op.operationId}\`.`, "");
      bodyTypes += `export type ${op.type}Response = ${tsResponse(op)};\n\n`;
    }
    if (op.pagination) {
      bodyTypes += jsdoc(`One item of the list \`${op.operationId}\` pages through.`, "");
      bodyTypes += `export type ${op.type}Item = ${ts(op.pagination.itemSchema, "")};\n\n`;
    }
  }
  out += bodyTypes;

  out += `/** Runtime description of every operation of ${k.id} (path, method, pagination…). */\n`;
  out += `export const operations = {\n`;
  for (const op of k.ops)
    out += `  ${JSON.stringify(op.ts)}: ${JSON.stringify(operationInfo(op))},\n`;
  out += `} as const satisfies Record<string, OperationInfo>;\n\n`;

  out += jsdoc(`${k.id}${k.description ? `\n\n${k.description}` : ""}`, "");
  out += `export interface ${k.type}Api {\n`;
  for (const op of k.ops) {
    const params = tsParameters(op) ? `${op.type}Params` : "void";
    out += jsdoc(operationDoc(op), "  ");
    out += op.flow
      ? `  readonly ${op.ts}: StreamOperation<${params}, ${op.type}Event>;\n`
      : op.pagination
        ? `  readonly ${op.ts}: PageableOperation<${params}, ${op.type}Response, ${op.type}Item>;\n`
        : `  readonly ${op.ts}: Operation<${params}, ${op.type}Response>;\n`;
  }
  out += `}\n`;

  const used = ["OperationInfo", "Operation"];
  if (k.ops.some((o) => o.pagination && !o.flow)) used.push("PageableOperation");
  if (k.ops.some((o) => o.flow)) used.push("StreamOperation");
  if (usesProblem.test(bodyTypes)) used.push("Problem");
  if (usesRedirect.test(bodyTypes)) used.push("RedirectResult");
  if (!k.ops.some((o) => !o.pagination && !o.flow)) used.splice(used.indexOf("Operation"), 1);
  out = out.replace(
    `import type { OperationInfo, Operation, PageableOperation, StreamOperation, Problem, RedirectResult } from "../../api/types";`,
    `import type { ${used.join(", ")} } from "../../api/types";`
  );
  return out;
}

